export interface ExtrasMeasure {
  /**
   * Документ, який прохід ФАКТИЧНО виміряв.
   *
   * Доти, доки цього поля не було, `extras` лишався єдиним із дванадцяти
   * проходів, який про себе нічого не казав, — і живий прогін 2026-08-17
   * показав ціну: коли посеред прогону відкрили другий документ,
   * `composition` відмовився («Вікна виміру прийшли з різних документів»), а
   * `extras` мовчки виміряв ЧУЖУ книжку й віддав `ok: true`. У звіт про
   * видання 190×220 мм лягли формат 175×250, виліт 0 і 5580 порожніх
   * абзаців замість 416. Помилки не було ніде: числа просто були не звідти.
   *
   * Порівнює це поле зі штампом сеансу `executePasses` — в одному місці на
   * всі проходи, а не копією правила тут.
   */
  docName: string;
  horizontalScaleOffenders: Array<{ page: string; style: string; scale: number; count: number }>;
  emptyParagraphs: number;
  forcedBreaks: { total: number; inBodyText: number };
  smallestPointSize: { pt: number; style: string; page: string } | null;
  thinnestStrokePt: number | null;
  pasteboardItems: Array<{ layer: string; count: number }>;
  /**
   * Елементи, чию сторінку визначити НЕ ВДАЛОСЯ.
   *
   * До 2026-08-18 такого стану не існувало: `parentPageOf` віддавав `null` і
   * для елемента на монтажному столі, і для елемента, читання якого КИНУЛО, —
   * і обидва рахувались у `pasteboardItems`. «Невідомо» видавало себе за
   * «точно поза сторінкою», і число тихо роздувалось.
   *
   * Необов'язкове (`?`) з тієї самої причини, що `pageFormat` нижче: фікстури
   * `ExtrasMeasure`, написані до цього поповнення, поля не мають, а
   * `npm run typecheck` уже бачить тести.
   */
  unresolvedItems?: number;
  /**
   * R19: рядки контрольної таблиці регресії (спек §10) — формат сторінки й
   * виліт. `doc_overview` їх не має, а `geometry_audit` міряє всередині
   * (`GeometryMeasure`), але не виносить у `GeometryReport`
   * (`src/tools/geometry.ts:155`). Тут — не дублювання: це єдине місце у
   * відповіді жодного інструмента, де ці числа взагалі доступні.
   *
   * `units` — одиниця, у якій ФАКТИЧНО виміряно (JSX міряє в пунктах, як і
   * `geometry_audit`, і кладе рядок "pt" явно). Підсумовувач НЕ перекладає
   * її сам: перекладення з непроговореною одиницею вже раз дало тиху
   * помилку в цьому проєкті (C2, Фаза 9). Що виміряно — те й друкується.
   *
   * Необов'язкові (`?`), а не обов'язкові: сам JSX-обробник завжди
   * заповнює обидва поля, але фікстури `ExtrasMeasure`, написані до цього
   * поповнення (`tests/unit/cli-sections.test.ts`, комміт e81b1a9, чужа
   * задача), їх не мають — а `npm run typecheck` УЖЕ бачить тести (перевірено
   * запуском: TS2739 на цьому самому файлі до цього виправлення). Зробити
   * поля обов'язковими означало б або зламати чужий, уже змерджений файл,
   * або редагувати його — обидва заборонені умовами цієї задачі.
   */
  pageFormat?: { width: number; height: number; units: string };
  bleed?: { top: number; bottom: number; inside: number; outside: number };

  /**
   * C3 (родина `sequences`, спек §4.4, рулінг R25): один запис на кожне
   * правило `sequences.rules[]` конфіга — 185 номерів питань «Нумерація
   * питань» вимірюється тут, а не `pagination_audit` (той інструмент
   * `rules` не приймає).
   *
   * `found` — скільки абзаців цього стилю знайдено; `parsed` — з них
   * скільки чисел вдалося розібрати. Обидва числа друкуються ЗАВЖДИ, разом,
   * навіть коли `breaks` порожній: нуль розривів при 185 абзацах і нуль
   * розривів при 3 розібраних із 185 виглядають однаково, якщо не
   * друкувати саме `parsed` (спек §5.4/§8 — «нуль без числа невідрізненний
   * від «не питали»»).
   *
   * `breaks` — ПЕРЕЛІК розривів (попереднє число, наступне число,
   * сторінка), А НЕ вирок «послідовно/ні». JSX-парсер номера — свій,
   * саморобний (§4.4 називає ціну: власний вимір не дублює наявний
   * інструмент, але й не має його точності), і нетипова форма запису
   * (напр. «12а») буде розібрана хибно. Перелік людина прочитає сама й
   * побачить, що це форма запису, а не дефект макета — голе
   * «НЕ ПОСЛІДОВНО» такої змоги не дає.
   *
   * `unparsed` — абзаци, з яких число не вичитується ВЗАГАЛІ (ні однієї
   * цифри на початку тексту). Окремий стан, не «пропущено мовчки»: якщо
   * розібралось лише 3 зі 185, `breaks.length === 0` сама по собі брехливо
   * заспокоює.
   *
   * Необов'язкове (`?`), тим самим способом, що `pageFormat`/`bleed` вище:
   * старі фікстури `ExtrasMeasure` (`tests/unit/cli-sections.test.ts`,
   * `tests/unit/cli-audit-report-assembly.test.ts`, чужі, вже змерджені
   * файли) написані до цього поля й не несуть його — обов'язкове поле тут
   * провалило б `npm run typecheck` (він бачить тести) чужим файлом, який
   * заборонено редагувати.
   *
   * `restarts` (раунд виправлень 1, Minor 5): скільки разів у ПОСЛІДОВНОСТІ
   * зустрілось число «1» — і, отже, скільки разів обхід НЕ перевіряв
   * розрив, покладаючись на евристику «1 = початок нового відрізка»
   * (`src/jsx/cli-extras.jsx`, `IDMCP.cliMeasureSequence`). На живому
   * документі — 12, по одному на розділ. Без цього числа рестарти
   * лишаються невидимими для читача звіту: він бачить «розривів немає» і
   * читає це як «суцільна нумерація», хоча насправді 12 відрізків
   * перевірено окремо один від одного, і жодна пара сусідніх «1» (справжній
   * дубль) розривом не стане.
   */
  sequences?: SequenceRuleMeasure[];
}

/**
 * Один запис `ExtrasMeasure.sequences[]` — вимір ОДНОГО правила
 * `sequences.rules[]`. Названий тип (не інлайн-об'єкт), бо раунд
 * виправлень 1 (Critical 1) навчив рядкові адаптери `sections.ts`/
 * `audit.ts` читати ЦЕ САМЕ поле — їм потрібне ім'я типу, а не структурна
 * сумісність навмання.
 */
export interface SequenceRuleMeasure {
  style: string;
  found: number;
  parsed: number;
  restarts: number;
  breaks: Array<{ prev: number; next: number; page: string }>;
  unparsed: Array<{ page: string; text: string }>;
}

/**
 * Скільки СПРАВЖНІХ проблем несе один запис `sequences[]` — структурне
 * число, а не рядки-речення `summariseExtras` (той самий принцип, яким уже
 * рахуються `масштаб`/`монтажнийСтіл`/`волосяне` в `sections.ts`, R22).
 *
 * Експортовано (Critical 1, раунд виправлень 1): `sections.ts` (лічильник
 * `count` для «чисто»/`needsEyes`) і `audit.ts` (рядки таблиці «crit»/
 * «major») мусять судити «є проблема чи ні» ОДНИМ і тим самим правилом —
 * інакше секція та таблиця розійшлися б, як `count`/`measured` уже раз
 * розходились у R22.
 *
 * `found === 0` рахується як РІВНО ОДНА проблема (стилю в документі
 * немає), навіть не маючи жодного розриву чи нерозпізнаного абзаца —
 * Important 2, той самий випадок, що `summariseExtras` тепер веде в
 * `findings`, а не в `clean`.
 */
export function countSequenceProblems(seq: SequenceRuleMeasure): number {
  if (seq.found === 0) return 1;
  return seq.breaks.length + seq.unparsed.length;
}

/**
 * Волосяна лінія — те, що друкарня фізично не відтворює.
 *
 * Експортовано (R22, рецензія задачі 12): рядковий адаптер `__cli_extras`
 * в `audit.ts` і адаптер лічильника в `sections.ts` мусять судити «волосяне
 * чи ні» ТИМ САМИМ порогом, що й цей модуль — дублювання числа магічною
 * константою в другому місці раніше чи пізніше розійшлося б.
 */
export const ВОЛОСЯНА_PT = 0.25;

/*
 * ============================================================================
 * ПОКАЗ ФОРМАТУ: ОКРУГЛЕННЯ Й МІЛІМЕТРИ (раунд виправлень 1, знахідка
 * контролера №2 — живий прогін).
 *
 * Вимірюється формат у ПУНКТАХ і так лишається: `src/jsx/cli-extras.jsx`
 * примусово ставить `MeasurementUnits.POINTS` на весь обхід, у
 * `measurements.json` іде сире число, і жодне з цього не змінюється. Тут —
 * ЛИШЕ показ, і саме тому переклад стоїть у звітному шарі, а не у вимірі:
 * «переклали одиницю, не проговоривши» в цьому проєкті вже двічі коштувало
 * (C2, Фаза 9).
 *
 * Що було на живому прогоні (справжня книжка, шапка звіту):
 *   538.582677165354 × 623.622047244095 pt,
 *   виліт 8.50393700787402/8.50393700787402/0/8.50393700787402 pt
 * Фізично правильно (це справді 190 × 220 мм і 3 мм вилету), але для
 * друкарні непридатне: п'ятнадцять знаків після коми читаються як шум, і
 * шум у шапці вчить не читати шапку.
 *
 * Міліметри показуються ПОРУЧ, а не замість: друкар думає про формат у
 * міліметрах, а перевірити вимір можна лише в тій одиниці, в якій він
 * зроблений. Коефіцієнт названий явно, а не вписаний числом 0.3528 — щоб
 * наступний бачив, звідки він (дюйм = 25.4 мм = 72 pt).
 * ============================================================================
 */

/** Міліметрів у пункті: дюйм — це 25.4 мм і рівно 72 пункти. */
const ММ_У_ПУНКТІ = 25.4 / 72;

/**
 * Число без хвоста нулів: 190 лишається «190», 538.58 — «538.58».
 * `toFixed` дав би «190.0» і «3.0», а зайвий нуль у шапці читається як
 * точність, якої в округленому числі вже немає.
 */
function короткеЧисло(n: number, знаків: number): string {
  const множник = 10 ** знаків;
  return String(Math.round(n * множник) / множник);
}

/**
 * Пункти → міліметри для ПОКАЗУ, з точністю до десятої: 8.50393700787402 pt
 * стає «3», 538.582677165354 pt — «190». Друкарський допуск грубіший за
 * десяту міліметра, тож дрібніша точність тут — та сама вигадана точність,
 * від якої й лікуємось.
 */
export function ммЗПунктів(pt: number): string {
  return короткеЧисло(pt * ММ_У_ПУНКТІ, 1);
}

/**
 * Самі пункти для показу — до сотої. Це вже не «сире число з InDesign», а
 * саме показ: сире лишається в `measurements.json`, яким порівнюються два
 * прогони (спек §4.2).
 */
export function пунктиКоротко(pt: number): string {
  return короткеЧисло(pt, 2);
}

/**
 * ОДНА довжина для показу — число без одиниці.
 *
 * Раунд виправлень 2, Minor 2: коментар при `форматСловами` стверджував, що
 * шапка й картка беруть формат з ОДНОЇ функції, а насправді спільним у них
 * був лише `ммЗПунктів`. Розбіжність була не уявна: на не-пунктовому вимірі
 * картка друкувала `короткеЧисло(…, 2)`, а плитка — сире `${f.width}`.
 * Сьогодні наслідків не було (`src/jsx/cli-extras.jsx:205` жорстко ставить
 * `units: "pt"`), але це рівно та пара «одна величина, два форматування»,
 * з якої виросли R22 та I6, — просто вона ще не встигла спрацювати.
 *
 * Обрано звести на СПРАВДІ одну функцію, а не переписати коментар: пара з
 * латентною розбіжністю дорожча за один параметр. Тепер кожна довжина, яку
 * звіт показує в одиниці ЗАМОВНИКА (міліметри, а при не-пунктовому вимірі —
 * його власна одиниця), йде крізь цю пару: розмір сторінки й виліт у шапці
 * (`форматСторінки`, `src/cli/audit.ts`) і ті самі два виміри в картці
 * «Перевірено чисто» (`summariseExtras` нижче). Показ у самих ПУНКТАХ —
 * окрема функція `пунктиКоротко`, і це не другий формат тієї самої
 * величини, а друга одиниця, названа в тексті поруч із числом.
 *
 * `units` перевіряється, а не припускається: коефіцієнт правдивий лише для
 * пунктів, тож інша одиниця друкується сама собою — округленою, але не
 * перекладеною.
 */
export function довжинаЧислом(n: number, units: string): string {
  return units === "pt" ? ммЗПунктів(n) : короткеЧисло(n, 2);
}

/** Підпис одиниці, у якій `довжинаЧислом` віддала число. */
export function довжинаОдиницею(units: string): string {
  return units === "pt" ? "мм" : units;
}

/**
 * Формат сторінки словами. `пунктиВДужках` — єдина відмінність двох
 * показів: картка «Перевірено чисто» несе ще й сам вимір у пунктах (там є
 * місце й там його перевіряють), плитка шапки — ні (вона вузька,
 * `minmax(132px,1fr)`, а пункти стоять поруч на тій самій сторінці).
 * Числа в обох — з `довжинаЧислом` вище.
 */
export function форматСловами(
  f: { width: number; height: number; units: string },
  { пунктиВДужках }: { пунктиВДужках: boolean },
): string {
  const розмір =
    `${довжинаЧислом(f.width, f.units)} × ${довжинаЧислом(f.height, f.units)} ` +
    довжинаОдиницею(f.units);
  if (!пунктиВДужках || f.units !== "pt") return розмір;
  return `${розмір} (${пунктиКоротко(f.width)} × ${пунктиКоротко(f.height)} pt)`;
}

/**
 * Нуль іде в «чисто» З ЧИСЛОМ, а не зникає: без числа нуль невідрізненний
 * від «не питали» (спек §8).
 */
export function summariseExtras(m: ExtrasMeasure): { clean: Bi[]; findings: Bi[] } {
  const clean: Bi[] = [];
  const findings: Bi[] = [];

  if (m.horizontalScaleOffenders.length === 0) {
    clean.push(bi("Горизонтальний масштаб абзаців: усі 100 %", "Horizontal scale of paragraphs: all 100 %"));
  } else {
    for (const o of m.horizontalScaleOffenders) {
      findings.push(
        bi(
          `Горизонтальний масштаб ${o.scale} % — с. ${o.page}, стиль «${o.style}», ${o.count} абз.`,
          `Horizontal scale ${o.scale} % — p. ${o.page}, style “${o.style}”, ${o.count} paragraphs`,
        ),
      );
    }
  }

  clean.push(bi(`Порожніх абзаців: ${m.emptyParagraphs}`, `Empty paragraphs: ${m.emptyParagraphs}`));
  clean.push(
    bi(
      `Примусових розривів: ${m.forcedBreaks.total}, з них в основному тексті ${m.forcedBreaks.inBodyText}`,
      `Forced breaks: ${m.forcedBreaks.total}, of them in body text ${m.forcedBreaks.inBodyText}`,
    ),
  );

  /*
   * Раунд виправлень 2, Minor 3: кегль і обведення друкувались СИРИМИ, за
   * два рядки від щойно округленого формату. У цій книжці обидва виявились
   * круглими, тож дефекту в живому звіті не було — але `0.24999999999999997 pt`
   * дав би рівно ту саму скаргу, що й `538.582677165354`, і коштує це один
   * виклик. Округлюється ПОКАЗ; порівняння з `ВОЛОСЯНА_PT` нижче лишається
   * на СИРОМУ числі — округлений поріг зробив би з межі лотерею.
   *
   * Ціна округлення, названа тут, щоб її не «виправили» назад: на волосині
   * від межі (0.2499…) показ дає ті самі «0.25 pt», що й поріг, і речення
   * читається як «0.25 тонше за 0.25». Знахідка при цьому спрацьовує
   * ПРАВИЛЬНО (порівняння на сирому), а вужчого показу тут не заводжу
   * навмисно: друге правило округлення для тієї самої величини — рівно та
   * пара, з якої виросли R22, I6 та Minor 2 цього раунду.
   */
  if (m.smallestPointSize !== null) {
    clean.push(
      bi(
        `Найдрібніший кегль: ${пунктиКоротко(m.smallestPointSize.pt)} pt ` +
          `(«${m.smallestPointSize.style}», с. ${m.smallestPointSize.page})`,
        `Smallest point size: ${пунктиКоротко(m.smallestPointSize.pt)} pt ` +
          `(“${m.smallestPointSize.style}”, p. ${m.smallestPointSize.page})`,
      ),
    );
  }

  if (m.thinnestStrokePt !== null) {
    if (m.thinnestStrokePt < ВОЛОСЯНА_PT) {
      findings.push(
        bi(
          `Волосяне обведення ${пунктиКоротко(m.thinnestStrokePt)} pt — ` +
            `тонше за ${ВОЛОСЯНА_PT} pt друкарня не відтворює.`,
          `Hairline stroke ${пунктиКоротко(m.thinnestStrokePt)} pt — ` +
            `a print shop cannot reproduce anything thinner than ${ВОЛОСЯНА_PT} pt.`,
        ),
      );
    } else {
      clean.push(
        bi(
          `Найтонше обведення: ${пунктиКоротко(m.thinnestStrokePt)} pt; волосяних немає`,
          `Thinnest stroke: ${пунктиКоротко(m.thinnestStrokePt)} pt; no hairlines`,
        ),
      );
    }
  }

  /*
   * Minor із рецензії раунду 1: порожній масив раніше просто нічого не
   * додавав — нуль зникав мовчки, на відміну від усіх інших полів цього
   * підсумовувача. Порожньо — теж вимір, і йде в «чисто» з нулем.
   */
  if (m.pasteboardItems.length === 0) {
    clean.push(bi("На монтажному столі: 0 об'єктів", "On the pasteboard: 0 objects"));
  } else {
    for (const p of m.pasteboardItems) {
      findings.push(
        bi(
          `На монтажному столі: ${p.count} об'єктів на шарі «${p.layer}»`,
          `On the pasteboard: ${p.count} objects on layer “${p.layer}”`,
        ),
      );
    }
  }

  /*
   * §2.6: «НЕ ВИЗНАЧИЛИ» ≠ «ТОЧНО ПОЗА СТОРІНКОЮ», і саме тому це окремий
   * рядок, а не доданок до числа вище.
   *
   * Доти обидва стани зливались в один `null`, і елемент, про який відомо
   * лише «прочитати не вдалося», потрапляв у `pasteboardItems` як доведено
   * позасторінковий — лічильник тихо роздувався. Тепер їх розводить
   * `IDMCP.pageResolution`, і невизначені мають власне число.
   *
   * Іде у findings, а не в clean: це не дефект макета, але й не «чисто» —
   * це межа приладу, названа числом. Нуль сюди не друкується (на відміну від
   * монтажного столу вище): «не визначили жодного» — нормальний стан кожного
   * здорового прогону, і рядок про нього був би шумом у КОЖНОМУ звіті.
   */
  if ((m.unresolvedItems ?? 0) > 0) {
    findings.push(
      bi(
        `Сторінку НЕ визначено для ${m.unresolvedItems} об'єктів — це «не змогли прочитати», ` +
          "а не «на монтажному столі»: у число вище вони НЕ входять.",
        `A page was NOT determined for ${m.unresolvedItems} objects — that is “we could not read them”, ` +
          "not “on the pasteboard”: they are NOT included in the number above.",
      ),
    );
  }

  /*
   * Захисна перевірка на присутність — поля НЕОБОВ'ЯЗКОВІ саме тому (див.
   * коментар при `ExtrasMeasure`): фікстура в `tests/unit/cli-sections.
   * test.ts` (чужий, уже змерджений файл) написана до R19 і цих двох полів
   * не має. `npm run typecheck` це БАЧИТЬ (тести включені в
   * tsconfig.typecheck.json з 2026-08-05), тож зробити поля обов'язковими
   * означало б провалити гейт чужим файлом, який заборонено редагувати.
   * `vitest` типів не перевіряє (esbuild), тож без цієї перевірки виклик
   * на старій фікстурі впав би в РАНТАЙМІ з `TypeError` — рівно так само,
   * як m.smallestPointSize/thinnestStrokePt вище вже обробляють свою
   * відсутність через `!== null`.
   */
  if (m.pageFormat && m.bleed) {
    const u = m.pageFormat.units;
    const формат = форматСловами(m.pageFormat, { пунктиВДужках: true });
    clean.push(bi(`Формат сторінки: ${формат}`, `Page format: ${формат}`));
    /*
     * Виліт — у міліметрах, бо саме в них його замовляють друкарні, і з
     * пунктами в дужках, бо в них він виміряний. Одиниця виліту та сама, що
     * у формату (обидва читає той самий обхід із примусовими пунктами), тож
     * і числа йдуть крізь ту саму `довжинаЧислом`, що й формат (Minor 2):
     * інша одиниця друкується сама собою, округленою, але не перекладеною.
     */
    const мм = (pt: number): string => `${довжинаЧислом(pt, u)} ${довжинаОдиницею(u)}`;
    const пункти =
      u === "pt"
        ? `${пунктиКоротко(m.bleed.top)}/${пунктиКоротко(m.bleed.bottom)}/` +
          `${пунктиКоротко(m.bleed.inside)}/${пунктиКоротко(m.bleed.outside)}`
        : null;
    clean.push(
      bi(
        `Виліт: зверху ${мм(m.bleed.top)}, знизу ${мм(m.bleed.bottom)}, ` +
          `зсередини ${мм(m.bleed.inside)}, ззовні ${мм(m.bleed.outside)}` +
          (пункти === null ? "" : ` (у пунктах: ${пункти})`),
        `Bleed: top ${мм(m.bleed.top)}, bottom ${мм(m.bleed.bottom)}, ` +
          `inside ${мм(m.bleed.inside)}, outside ${мм(m.bleed.outside)}` +
          (пункти === null ? "" : ` (in points: ${пункти})`),
      ),
    );
  }

  /*
   * C3: одна родина `sequences.rules[]` — один запис масиву. `found` і
   * `parsed` друкуються РАЗОМ і ЗАВЖДИ (навіть у «чисто»): без `parsed`
   * нуль розривів при 185 абзацах і нуль розривів при 3 розібраних із 185
   * виглядали б однаково (див. коментар при `ExtrasMeasure.sequences`).
   *
   * «Чисто» — лише коли ВСІ абзаци розібрались І розривів немає:
   * `unparsed.length > 0` при `breaks.length === 0` НЕ йде в «чисто» —
   * «розривів немає» з розібраних 3 зі 185 нічого не стверджує про
   * послідовність насправді, і мовчати про це означало б повторити той
   * самий тихий нуль, від якого рятує `parsed`.
   *
   * Important 2 (раунд виправлень 1): `found === 0` — стилю в документі
   * НЕМАЄ (описка в назві, або повний шлях замість барого імені — задача A
   * виміряла, що повний шлях резолвиться в НІЩО). До цієї правки
   * `breaks.length === 0 && unparsed.length === 0` було істинним і для
   * цього випадку теж, і правило з неіснуючим стилем друкувалось як
   * заспокійливе «0 абз., розібрано 0, розривів немає». Перевірка йде
   * ПЕРШОЮ, окремою гілкою: «стилю не знайдено» — не «чисто», а «нічого не
   * перевірено».
   */
  for (const seq of m.sequences ?? []) {
    if (seq.found === 0) {
      findings.push(
        bi(
          `Нумерація «${seq.style}»: стилю в документі не знайдено — нічого не перевірено.`,
          `Numbering “${seq.style}”: the style was not found in the document — nothing was checked.`,
        ),
      );
      continue;
    }
    const підсумок = bi(
      `Нумерація «${seq.style}»: ${seq.found} абз., розібрано ${seq.parsed}, ` +
        `рестартів нумерації: ${seq.restarts}`,
      `Numbering “${seq.style}”: ${seq.found} paragraphs, parsed ${seq.parsed}, ` +
        `numbering restarts: ${seq.restarts}`,
    );
    if (seq.breaks.length === 0 && seq.unparsed.length === 0) {
      clean.push(bi(`${підсумок.uk}, розривів немає`, `${підсумок.en}, no gaps`));
    } else {
      findings.push(
        bi(
          `${підсумок.uk} — розривів: ${seq.breaks.length}, нерозпізнаних чисел: ${seq.unparsed.length}`,
          `${підсумок.en} — gaps: ${seq.breaks.length}, unrecognised numbers: ${seq.unparsed.length}`,
        ),
      );
      for (const b of seq.breaks) {
        findings.push(
          bi(
            `Нумерація «${seq.style}»: розрив ${b.prev} → ${b.next} — с. ${b.page}`,
            `Numbering “${seq.style}”: gap ${b.prev} → ${b.next} — p. ${b.page}`,
          ),
        );
      }
      for (const unp of seq.unparsed) {
        findings.push(
          bi(
            `Нумерація «${seq.style}»: число не розпізнано — с. ${unp.page}, текст «${unp.text}»`,
            `Numbering “${seq.style}”: number not recognised — p. ${unp.page}, text “${unp.text}”`,
          ),
        );
      }
    }
  }

  return { clean, findings };
}
