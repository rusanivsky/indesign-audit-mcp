/* Зонд H13, габарит ПОВЕРНУТОЇ рамки — ПІДСТАВА РІШЕННЯ I3.
 *
 * Документ створюється власний і закривається `SaveOptions.NO`. Робочої
 * книжки зонд не торкається взагалі.
 *
 * ПИТАННЯ. Що саме `geometricBounds` віддає для повернутого елемента:
 *   (а) щільну ОСЕОРІЄНТОВАНУ ОБОЛОНКУ повернутої фігури, чи
 *   (б) саму (неповернуту) рамку в її власній системі координат?
 *
 * НАВІЩО. Від цього залежить, чи однаково гейтувати повернені рамки у двох
 * детекторах родини `frame`:
 *   - `detectNearMiss` (вирівнювання) виключає їх;
 *   - `detectOffPage` (вихід за виліт) — ні,
 * і рецензія слушно назвала це непослідовністю: або габарит годиться для
 * вироку, або ні.
 *
 * Відповідь різна для двох різних питань, і саме тому гейт потрібен ОДНОМУ:
 *   - СТОРОНИ оболонки не є сторонами рамки ⇒ «чи пристала межа рамки до
 *     межі колонки» за нею не вирішується → гейт у near-miss лишається;
 *   - оболонка ЩІЛЬНА ⇒ вона перетинає межу вильоту тоді й лише тоді, коли
 *     за неї виходить якийсь КУТ рамки → вирок про вихід точний, і гейт був
 *     би втратою справжніх знахідок (на книжці це 91 рамка).
 *
 * ЧОМУ 45°, А НЕ ЛИШЕ −90°. На −90° проста перестановка сторін (40×300)
 * виглядає точно так само, як щільна оболонка, — цей кут не розрізняє (а) і
 * (б) взагалі. Розрізняє довільний кут: для прямокутника 300×40 щільна
 * оболонка на 45° мусить бути квадратом зі стороною (300+40)/√2 = 240,4163.
 *
 * ВИМІРЯНО 2026-08-15 (InDesign 21.5.1.73):
 *
 *   до повороту            [100, 100, 140, 400]        300 × 40
 *   після rotationAngle=−90 [100, 60, 400, 100]         40 × 300
 *   після rotationAngle=45  [−112,1320, 100,
 *                            128,2843, 340,4163]        240,4163 × 240,4163
 *
 *   (300 + 40) / √2 = 240,416305603426 — збіг ТОЧНИЙ,
 *   і `visibleBounds` дає ті самі числа.
 *
 * ВИСНОВОК: варіант (а). Габарит — щільна осеорієнтована оболонка.
 */

var previousUnit = app.scriptPreferences.measurementUnit;
app.scriptPreferences.measurementUnit = MeasurementUnits.POINTS;

var out = { threw: [] };
var doc = null;

try {
    doc = app.documents.add();
    var pg = doc.pages[0];

    /* Прямокутник НЕквадратний навмисно: на квадраті будь-який поворот на
     * 90° не змінив би нічого, і зонд не розрізнив би гіпотез. */
    var tf = pg.textFrames.add();
    tf.geometricBounds = [100, 100, 140, 400];

    var b0 = tf.geometricBounds;
    out.before = [b0[0], b0[1], b0[2], b0[3]];
    out.beforeW = b0[3] - b0[1];
    out.beforeH = b0[2] - b0[0];

    /* --- Контроль 1: −90°. Очікується перестановка сторін; цей кут САМ ПО
     * СОБІ гіпотез не розрізняє, і він тут саме як контроль. ------------- */
    tf.rotationAngle = -90;
    var b1 = tf.geometricBounds;
    out.after90 = [b1[0], b1[1], b1[2], b1[3]];
    out.after90W = b1[3] - b1[1];
    out.after90H = b1[2] - b1[0];

    /* --- Вирішальний вимір: 45°. --------------------------------------- */
    tf.rotationAngle = 45;
    var b2 = tf.geometricBounds;
    out.after45 = [b2[0], b2[1], b2[2], b2[3]];
    out.after45W = b2[3] - b2[1];
    out.after45H = b2[2] - b2[0];

    /* Що дала б кожна з гіпотез: */
    out.hullExpected = (300 + 40) / Math.sqrt(2); // (а) щільна оболонка
    out.rawExpectedW = 300;                        // (б) сама рамка
    out.rawExpectedH = 40;

    out.isHull = (Math.abs(out.after45W - out.hullExpected) < 0.001) &&
                 (Math.abs(out.after45H - out.hullExpected) < 0.001);

    /* `visibleBounds` як незалежна перевірка того самого. */
    var v = tf.visibleBounds;
    out.visible45 = [v[0], v[1], v[2], v[3]];
    out.visibleAgrees = (Math.abs(v[0] - b2[0]) < 0.001) &&
                        (Math.abs(v[1] - b2[1]) < 0.001) &&
                        (Math.abs(v[2] - b2[2]) < 0.001) &&
                        (Math.abs(v[3] - b2[3]) < 0.001);
} catch (fatal) {
    out.fatal = String(fatal) + (fatal.line ? (" (рядок " + fatal.line + ")") : "");
} finally {
    /* Документ ВЛАСНИЙ, тож закриття безумовне — і саме в finally, щоб
     * невдалий вимір не лишив по собі відкритого документа, який потім
     * тихо зіпсує інтеграційний набір (він падає від стороннього
     * відкритого документа без жодного натяку в повідомленні). */
    if (doc !== null && doc.isValid) doc.close(SaveOptions.NO);
    app.scriptPreferences.measurementUnit = previousUnit;
}

out.openDocs = app.documents.length;
__result = out;
