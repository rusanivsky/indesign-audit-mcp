import { defineConfig } from "vitest/config";

/*
 * A4, раунд 3 — знахідка координатора, підтверджена емпірично (з InDesign
 * запущеним): `fileParallelism` усередині `projects[].test` НІЧОГО не
 * робить у Vitest 3 — це чисто кореневий перемикач планувальника. Той самий
 * прогін показав, що `testTimeout` так само НЕ успадковується з кореня в
 * проєкт (тест, що раніше вкладався в 60с, впав на дефолтних 5000ms, щойно
 * з'явився масив `projects`) — тож усе, що має діяти в конкретному проєкті,
 * тепер продубльовано явно в НЬОГО, а не покладається на корінь.
 *
 * fileParallelism: false лишається кореневим і діє на ВЕСЬ прогін, зокрема
 * на "unit" — юніт-тести не звертаються до InDesign, тож послідовний прогін
 * коштує їм лише швидкості (перевірено: 192 тести все одно проходять менш
 * ніж за секунду), а не коректності. Проєктний `fileParallelism: true` в
 * "unit" тут лишений як задокументований намір на майбутнє: якщо Vitest
 * колись почне поважати цю опцію на рівні проєкту, юніт-прогін пришвидшиться
 * без додаткових змін конфігу.
 */
export default defineConfig({
  test: {
    testTimeout: 60_000,
    fileParallelism: false,
    projects: [
      {
        test: {
          name: "unit",
          include: ["tests/unit/**/*.test.ts"],
          testTimeout: 60_000,
          /* Юніт-тести не звертаються до жодного зовнішнього процесу — цей
           * перемикач нічого не змінює на практиці (fileParallelism —
           * кореневий), але лишаємо як намір: юніт-файли одне одному не
           * заважають, на відміну від інтеграційних. */
          fileParallelism: true,
        },
      },
      {
        test: {
          name: "integration",
          include: ["tests/integration/**/*.test.ts"],
          testTimeout: 60_000,
          /*
           * Інтеграційні тести керують ОДНИМ спільним живим процесом InDesign.
           * У InDesign лише один документ "активний" — якщо кілька файлів
           * одночасно створюють фікстури, вони змагаються за це глобальне поле.
           * Реальну послідовність дає кореневий fileParallelism: false вище —
           * це поле тут суто документує намір на випадок, якщо Vitest колись
           * почне поважати його на рівні проєкту.
           */
          fileParallelism: false,
          /* A4: фікстурні обробники доступні лише тут. */
          env: { INDESIGN_MCP_FIXTURES: "1" },
          /*
           * Прибирання забутих фікстур ДО і ПІСЛЯ всього прогону. Навіщо це
           * поверх `afterEach` у кожному файлі — пояснено в самому файлі.
           */
          globalSetup: ["tests/integration/global-fixture-sweep.ts"],
        },
      },
    ],
  },
});
