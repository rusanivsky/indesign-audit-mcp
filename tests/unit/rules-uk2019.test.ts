import { describe, expect, it } from "vitest";
import { rewrite, runRules } from "../../src/typography/engine.js";
import { UK2019_RULES } from "../../src/typography/rules-uk.js";

const fix = (text: string) => rewrite(text, runRules(text, UK2019_RULES));
const ids = (text: string) => runRules(text, UK2019_RULES).map((m) => m.ruleId);

describe("uk2019-proiekt", () => {
  it("править основу й похідні", () => {
    expect(fix("проект, проекція, проектування, спроектувати"))
      .toBe("проєкт, проєкція, проєктування, спроєктувати");
  });

  it("зберігає регістр", () => {
    expect(fix("Проект")).toBe("Проєкт");
    expect(fix("ПРОЕКТ")).toBe("ПРОЄКТ");
  });

  it("ІДЕМПОТЕНТНЕ: правильну форму не чіпає (а неправильну — таки править)", () => {
    expect(runRules("проєкт", UK2019_RULES)).toEqual([]);
    expect(fix("проект")).toBe("проєкт");
  });

  it("не чіпає інших слів із «ое» (а «проект» поруч — таки править)", () => {
    expect(fix("поет написав поему про Європу")).toBe("поет написав поему про Європу");
    expect(fix("проект")).toBe("проєкт");
  });

  it("правило прив'язане до української", () => {
    const rule = UK2019_RULES.find((r) => r.id === "uk2019-proiekt");
    expect(rule!.language).toBe("Ukrainian");
  });
});

describe("uk2019-sviashchennyk", () => {
  it("править лему й відмінкові форми", () => {
    expect(fix("священик і священика")).toBe("священник і священника");
  });

  it("зберігає регістр, включно з великими літерами", () => {
    expect(fix("Священик")).toBe("Священник");
    expect(fix("СВЯЩЕНИК")).toBe("СВЯЩЕННИК");
  });

  it("не колапсує нестандартний регістр — дублює саме те «н», що вже в збігу", () => {
    expect(fix("СВЯЩЕНик")).toBe("СВЯЩЕННик");
  });

  it("ІДЕМПОТЕНТНЕ: «священник» уже правильний (а «священик» — ні)", () => {
    expect(ids("священник")).toEqual([]);
    expect(ids("священик")).toEqual(["uk2019-sviashchennyk"]);
  });

  it("правило прив'язане до української", () => {
    const rule = UK2019_RULES.find((r) => r.id === "uk2019-sviashchennyk");
    expect(rule!.language).toBe("Ukrainian");
  });
});

describe("uk2019-compound", () => {
  it("зліплює компонент із наступним словом", () => {
    expect(fix("веб-сайт, архі-важливий, анти-вірус, псевдо-наука"))
      .toBe("вебсайт, архіважливий, антивірус, псевдонаука");
  });

  it("зберігає регістр першої літери компонента", () => {
    expect(fix("Веб-сайт")).toBe("Вебсайт");
  });

  it("НЕ чіпає дефіса перед ВЕЛИКОЮ літерою — там власна назва", () => {
    /* Виняток названий у самому джерелі: «пан-Європа», «екс-Югославія»,
     * «веб-API». Позитивний близнюк одразу поруч. */
    expect(ids("екс-Югославія, пан-Європа, веб-API")).toEqual([]);
    expect(ids("екс-чемпіон")).toEqual(["uk2019-compound"]);
  });

  it("НЕ чіпає компонента, що стоїть усередині іншого слова", () => {
    /* «стоп-кадр» містить «топ», «експрес-доставка» містить «прес» —
     * обидва мусять лишитися недоторканими. */
    expect(ids("стоп-кадр, експрес-доставка")).toEqual([]);
    expect(ids("топ-модель")).toEqual(["uk2019-compound"]);
  });

  it("довший компонент виграє над коротшим", () => {
    expect(fix("економ-клас")).toBe("економклас");
  });

  it("ІДЕМПОТЕНТНЕ: злите слово збігом не є (а розділене — є)", () => {
    expect(ids("вебсайт")).toEqual([]);
    expect(ids("веб-сайт")).toEqual(["uk2019-compound"]);
  });

  it("компонент-омограф понижується до сумнівного, а не пишеться мовчки", () => {
    /* «пара-трійка» — це два рівноправні слова через дефіс, а не префікс.
     * Такий збіг не викидається (він може бути й справжнім), а йде в
     * needs-review: typography_apply за замовчуванням його НЕ застосує. */
    const m = runRules("пара-трійка", UK2019_RULES);
    expect(m).toHaveLength(1);
    expect(m[0]!.confidence).toBe("needs-review");

    /* Позитивний близнюк: не-омограф лишається впевненим. */
    expect(runRules("веб-сайт", UK2019_RULES)[0]!.confidence).toBe("high");
  });

  it("НЕ зліплює компонент із ЛАТИНСЬКИМ словом (а з кириличним — таки зліплює)", () => {
    /* Гейт мовний, а не послівний: латинське слово всередині українського
     * діапазону лишається всередині нього, і збіг тут писався б без
     * підтвердження — confidence high. */
    expect(ids("смарт-tv, веб-preview")).toEqual([]);
    expect(ids("смарт-годинник")).toEqual(["uk2019-compound"]);
  });

  it("правило прив'язане до української", () => {
    const rule = UK2019_RULES.find((r) => r.id === "uk2019-compound");
    expect(rule!.language).toBe("Ukrainian");
  });
});
