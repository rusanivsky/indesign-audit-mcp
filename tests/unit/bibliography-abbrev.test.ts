import { describe, expect, it } from "vitest";
import { isKnownAbbreviation } from "../../src/bibliography/abbrev.js";
import { abbrevRule } from "../../src/bibliography/rules-dstu.js";
import { parseRecord } from "../../src/bibliography/parse.js";

const parse = (t: string) => parseRecord({
  number: 50, text: t, containerId: "story:0", start: 0, end: t.length, page: "20",
});

describe("isKnownAbbreviation", () => {
  it("знає базовий лексикон", () => {
    for (const w of ["зб.", "наук.", "пр.", "вид.", "ун-ту", "б-ка", "т-во", "упоряд.", "Вип.", "с."]) {
      expect(isKnownAbbreviation(w)).toBe(true);
    }
  });

  it("знає відмінкові форми «б-ка»", () => {
    /* Рецензія: NO_DOT згадував "б-ки"/"б-ці", але BASE їх не мав, тож у
     * лексикон вони не потрапляли попри членство в NO_DOT. */
    for (const w of ["б-ки", "б-ці"]) {
      expect(isKnownAbbreviation(w)).toBe(true);
    }
  });

  it("знає складні скорочення через дефіс", () => {
    /* 394 і 395 законних збігів на двох випусках серії — спек §10.9. */
    for (const w of ["наук.-практ.", "іст.-краєзн.", "авт.-упоряд.", "наук.-теорет."]) {
      expect(isKnownAbbreviation(w)).toBe(true);
    }
  });

  it("не знає вигаданого", () => {
    expect(isKnownAbbreviation("бздщ.")).toBe(false);
  });
});

describe("abbrevRule", () => {
  it("знахідка ЗАВЖДИ needs-review, ніколи high", () => {
    /*
     * Спек §2: лексикон 3582 не покриває назв установ, серій і периодики, тож
     * упевнений вердикт тут був би брехнею.
     */
    const t = "50. Прізвище, Ім'я. Назва : зб. бздщ. пр. / І. П. Прізвище // Журнал. – 2024. – С. 5-9.";
    const f = abbrevRule.check(parse(t), "7.1");
    expect(f.length).toBeGreaterThan(0);
    for (const x of f) expect(x.confidence).toBe("needs-review");
  });

  it("мовчить на відомих скороченнях", () => {
    const t = "50. Прізвище, Ім'я. Назва : зб. наук. пр. / І. П. Прізвище // Журнал. – 2024. – С. 5-9.";
    expect(abbrevRule.check(parse(t), "7.1")).toEqual([]);
  });

  it("СВІДОМО мовчить на невідомому слові в зоні заголовка — межа без словника імен", () => {
    /*
     * Позиція по батькові граматично це «Велика літера + літери + крапка», і
     * відрізнити спотворене слово від справжнього імені без словника особових
     * імен неможливо. Альтернатива — хибне спрацювання на КОЖНОМУ записі з
     * особистим заголовком. Якщо цей тест колись почне падати, це означає, що
     * хтось зняв виняток — і треба свідомо переоцінити обмін, а не «полагодити».
     */
    const t = "50. Прізвище, Ім'я Ксвкпр. Назва : зб. наук. пр. / І. П. Прізвище // Журнал. – 2024. – С. 5-9.";
    expect(abbrevRule.check(parse(t), "7.1")).toEqual([]);
  });

  /*
   * Знахідка M7: `suggested` дорівнював самому слову — 7 555 «пропозицій» на
   * книжці, кожна тотожна тексту. Пропозиція, що нічого не міняє, — це шум,
   * який іще й запрошує автоматичне застосування (заміна слова на нього
   * самого). Правило ставить ПИТАННЯ, а не пропонує заміну.
   */
  it("НЕ пропонує заміни, тотожної тексту", () => {
    const t = "50. Прізвище, Ім'я. Назва : зб. бздщ. пр. / І. П. Прізвище // Журнал. – 2024. – С. 5-9.";
    const f = abbrevRule.check(parse(t), "7.1");
    expect(f.length).toBeGreaterThan(0);
    for (const x of f) {
      expect(x.suggested).toBe("");
      expect(x.suggested).not.toBe(x.before);
    }
  });

  /*
   * Наслідок виправлення C1: скорочення в КІНЦІ абзацу. Раніше `\r` мовчки
   * виглядав як пробіл і збігався з `H`; відколи він лишається `\r`, лукагед
   * мусить називати його явно — інакше знахідка зникає без сліду. Виміряно на
   * дампі story 141: 9 знахідок із 1944.
   */
  it("ловить скорочення в кінці абзацу, а не лише перед пробілом", () => {
    const t = "50. Прізвище, Ім'я. Назва : зб. бздщ.\rпр. / І. П. Прізвище // Журнал. – 2024. – С. 5-9.";
    const f = abbrevRule.check(parse(t), "7.1");
    expect(f.some((x) => x.before === "бздщ.")).toBe(true);
    /* Сама знахідка вказує на СЛОВО, не на знак абзацу. */
    for (const x of f) expect(x.before).not.toContain("\r");
  });
});

/*
 * ЗАГОЛОВОК БЕЗ КОМИ — ТЕЖ ЗАГОЛОВОК.
 *
 * Зону «heading» парсер створює ЛИШЕ за наявності коми (`parse.ts`, HEADING
 * несе `,` літералом). Отже на «12. Шевченко Тарас Григорович.» зони не було,
 * виняток не мав за що зачепитися, і по батькові звітувалося як невідоме
 * скорочення.
 *
 * Найгірше, що це РІВНО ті записи, які вже позначає bib-heading-form: запис
 * без коми діставав ДВІ знахідки, і друга була хибною — редактор, виправивши
 * кому, побачив би, що «скорочення» зникло само.
 */
describe("виняток заголовка без коми", () => {
  const abbrev = (t: string) =>
    abbrevRule.check(parse(t), "7.1").map((f) => t.slice(f.start, f.end));

  it("по батькові в заголовку БЕЗ коми не звітується як скорочення", () => {
    expect(abbrev("12. Шевченко Тарас Григорович. Кобзар. – Київ : Наука, 2020. – 240 с.")).toEqual(
      [],
    );
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: із комою — так само нічого (як і було)", () => {
    expect(abbrev("12. Шевченко, Тарас Григорович. Кобзар. – Київ : Наука, 2020. – 240 с.")).toEqual(
      [],
    );
  });

  it("НЕГАТИВНИЙ КОНТРОЛЬ: скорочення ПОЗА заголовком досі ловиться", () => {
    /* Інакше правка звелася б до «родина bib-abbrev мовчить»: межа заголовка
     * не сміє поглинути весь запис. */
    expect(
      abbrev("12. Шевченко Тарас Григорович. Кобзар. – Київ : Ксвкпр. думка, 2020. – 240 с."),
    ).toEqual(["Ксвкпр."]);
  });
});
