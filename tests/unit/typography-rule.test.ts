/**
 * Шов `regexRule` — знахідка, яка нічого не міняє, знахідкою НЕ Є.
 *
 * ЗВІДКИ ЦЕ ВЗЯЛОСЬ. Повний прогін аудитів по робочій книжці 2026-08-15 дав
 * `typography_audit.totalMatches = 131`, з яких **107** — правило
 * `range-dash-numeric`, і в усіх 50 перевірених зразках `before === after`
 * побайтово. Причина не в книжці, а в самому правилі: клас пошуку
 * `HYPHENS` містить U+2013 — той самий символ, що стоїть у `replace`. Отже
 * після того, як книжку один раз нормалізували, правило матчить власний
 * вихід і доповідатиме його вічно.
 *
 * ЧОМУ ЦЬОГО НЕ ПОБАЧИЛИ 1900+ ТЕСТІВ. Усі наявні тести правил перевіряють
 * РЕЗУЛЬТАТ переписування (`fix(...)` → рядок), а порожня знахідка дає
 * рядок, тотожний вхідному — тобто для них вона невидима за побудовою.
 * Сусідній тест «тире, що вже стоїть, не чіпається» проходив і до
 * виправлення, і після: він дивиться на текст, а не на перелік знахідок.
 * Тому перевірка тут іде саме по ЗНАХІДКАХ (`match`/`runRules`).
 */
import { describe, expect, it } from "vitest";
import { regexRule } from "../../src/typography/rule.js";

describe("regexRule: збіг, що не змінює тексту", () => {
  const selfMatching = regexRule({
    id: "self-matching",
    title: "Клас пошуку містить символ заміни",
    confidence: "high",
    /* Рівно та сама конструкція, що в rules-uk: у пошуку і дефіс, і en-dash,
     * а на виході en-dash. */
    find: /(\d+)[-–](\d+)/gu,
    replace: "$1–$2",
  });

  it("НЕ віддає знахідку, коли заміна дослівно дорівнює знайденому", () => {
    expect(selfMatching.match("1941–1945")).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: справжню заміну віддає як і раніше", () => {
    const found = selfMatching.match("1941-1945");
    expect(found).toHaveLength(1);
    expect(found[0]?.replacement).toBe("1941–1945");
  });

  it("у змішаному тексті лишає тільки те, що справді треба правити", () => {
    /* Два входження: перше вже нормальне, друге — ні. */
    const found = selfMatching.match("1941–1945 і 2014-2022");
    expect(found).toHaveLength(1);
    expect(found[0]?.replacement).toBe("2014–2022");
    /* Адреса вказує саме на друге входження, а не з'їхала на перше. */
    expect("1941–1945 і 2014-2022".slice(found[0]!.start, found[0]!.end)).toBe("2014-2022");
  });

  it("правило, чия заміна ніколи не збігається зі знайденим, не постраждало", () => {
    const emDash = regexRule({
      id: "em-dash",
      title: "Дефіс між пробілами → довге тире",
      confidence: "high",
      find: / - /gu,
      replace: " — ",
    });
    expect(emDash.match("мама - це все")).toHaveLength(1);
    /* Власний вихід цим правилом уже не матчиться — U+2014 не в класі пошуку. */
    expect(emDash.match("мама — це все")).toEqual([]);
  });
});
