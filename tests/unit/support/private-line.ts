/**
 * Детектори приватного, спільні для ДВОХ воріт: файлових
 * (`tests/unit/privacy-gate.test.ts`) і воріт повідомлень комітів
 * (`tests/unit/commit-message-gate.test.ts`).
 *
 * ЧОМУ ОКРЕМИЙ МОДУЛЬ, А НЕ КОПІЯ. Детектор, скопійований у двоє воріт,
 * розходиться на першій же правці — рівно те, що описує `src/bibliography/
 * chars.ts` про класи символів. Тут ціна вища: розійшовшись, одні ворота
 * лишаться зеленими на тому, що другі вже ловлять, і зелень читатиметься як
 * «приватного немає».
 *
 * ЩО СЮДИ НЕ ПЕРЕЇХАЛО І НЕ ПЕРЕЇДЕ — ВЗІРЦІ. Позитивні близнюки (рядки, на
 * яких доводять, що детектор узагалі спрацьовує) лишаються у файлах тестів,
 * бо тільки там вони виправдані. Модуль несе САМІ ПРАВИЛА й жодного прикладу
 * приватних даних.
 *
 * Файл лежить під `tests/`, а не в `src/`: він не потрапляє у збірку і не
 * їде до споживача разом із сервером.
 */

import { createHash } from "node:crypto";

/**
 * Винятки — НАЗВАНІ ПОІМЕННО, а не через широкий шаблон.
 *
 * Кожен виняток мусить бути зрозумілим сам собою, інакше ворота тихо
 * розмиються до нуля: досить одного `/.*\/u`, щоб цей файл більше ніколи не
 * впав і при цьому лишався зеленим доказом «приватного немає».
 */
const ALLOWED = {
  /* Рядок авторського права — це ім'я АВТОРА ПРОГРАМИ, а не дані клієнта.
   * Воно там і має бути: без нього ліцензія не має власника. */
  licenseCopyright: (file: string) => file === "LICENSE",
  /* Синтетичний ISBN, навмисно вставлений у правило та його тести: він
   * ілюструє форму коду, за яку правило не сміє чіплятися. */
  syntheticIsbn: "978-966-1234-56-7",
  /* Той самий синтетичний код показано в тестах і ЗІПСОВАНИМ — з короткими
   * тире замість дефісів, бо саме так його спотворювало правило. Порівнюємо
   * після зведення всіх тире до дефіса, інакше ілюстрація дефекту читалася б
   * як ISBN справжнього видання. */
  dashesToHyphen: (v: string) => v.replace(/[\s‐‑–—]/gu, "-"),
  /* Поштові домени, зарезервовані RFC 2606 саме під приклади, плюс адреса,
   * якою підписуються коміти. */
  exampleMailHosts: /@(example\.(com|org|net)|users\.noreply\.github\.com|anthropic\.com)/u,
  /* Домашня тека-заповнювач у прикладах шляхів. `name` — той самий
   * заповнювач у документації («/Users/name/…»), а не чиясь домівка. */
  /* Межа заповнювача — САМЕ КІНЕЦЬ ТОКЕНА, а не `\b`. Спіймано мутацією
   * 2026-08-28: домівка, чия назва ПОЧИНАЄТЬСЯ зі слова-заповнювача й далі має
   * дефіс, проходила, бо межа слова збігається перед дефісом. Взірець тієї
   * форми стоїть у позитивному близнюку воріт, а не тут: цей файл несе
   * правила, і зайвий приклад робив би виняток для нього ширшим, ніж треба. */
  placeholderHome: /\/Users\/(designer|user|name|you|someone|path)(?=[/\\"'\s)\]]|$)/u,
  /* Уже знеособлений шлях до Drive: адресу згорнуто в три крапки або в
   * багатокрапку. Виняток НЕ покриває справжньої адреси — рівно ці дві форми. */
  elidedDrive: /GoogleDrive-(\.\.\.|…)/u,
  /* Шістнадцятковий колір (`#FFFFFF` у шаблоні звіту) — це запис КОЛЬОРУ, а не
   * слово. Виняток судить про ТОКЕН, а не про рядок: інакше один колір у рядку
   * прикривав би назву, що стоїть у тому ж рядку. */
  hexLiteral: /^#[0-9A-Fa-f]{3,8}$/u,
  /* Псевдонім супровідника чужого npm-пакета, який приїжджає в згенерований
   * `package-lock.json` (12 рядків із `sponsors/`). Це публічна адреса на
   * GitHub, а не приватні дані. Названо поіменно — чесніше, ніж вимкнути
   * ворота на цілому файлі: у lock-файлі бувають і справжні шляхи. */
  upstreamHandle: new Set(["Brooooooklyn"]),
};

/**
 * Токен, усередині якого стоїть ряд однакових літер (з `#` попереду, якщо він є).
 *
 * Потрібен, щоб виняток судив про саме слово, а не про весь рядок: рядок із
 * кольором і назвою поруч мусить лишитися спійманим.
 */
function tokenAt(line: string, index: number): string {
  let from = index;
  let to = index;
  while (from > 0 && /[\p{L}\p{N}#]/u.test(line[from - 1]!)) from -= 1;
  while (to < line.length && /[\p{L}\p{N}]/u.test(line[to]!)) to += 1;
  return line.slice(from, to);
}

/*
 * ФОРМА ЗАПИСУ — ЦЕ ТЕЖ СПОСІБ СХОВАТИСЯ, І ВІН СПРАЦЮВАВ.
 *
 * До 2026-08-27 ворота порівнювали рядок ЯК Є. `scripts/probe-textpath.raw.json`
 * пережив і чистку, і ці ворота з назвою другого видання всередині: macOS
 * віддав її в NFD (кожна «ї» — «і» + діереза), тож `grep` і regexp бачили інші
 * символи. Той самий клас — percent-кодування: `%D0%86%D1%81…` в URL шляху.
 *
 * Тому кожен рядок зводиться до однієї форми ПЕРЕД порівнянням: NFC, а тоді
 * percent-декодування (і знову NFC, бо декодоване теж буває розкладеним).
 * Некоректну послідовність `%` decodeURIComponent кидає — беремо тоді вихідне.
 */
function normalise(line: string): string {
  const nfc = line.normalize("NFC");
  let decoded = nfc;
  try {
    decoded = decodeURIComponent(nfc);
  } catch {
    /* не URL, а просто відсоток у тексті — порівнюємо як є */
  }
  return decoded.normalize("NFC");
}

/*
 * НАЗВА ВИДАННЯ ФОРМИ НЕ МАЄ — ТОЖ ТУТ ДВА РІЗНІ ПРИЙОМИ, І ЖОДЕН ІЗ НИХ НЕ
 * ЗБЕРІГАЄ НАЗВУ В РЕПОЗИТОРІЇ.
 *
 * Комент угорі пояснює, чому словник справжніх імен неприпустимий: він сам
 * став би переліком приватного. Те саме стосується назв. Тому:
 *
 *   - перша книжка має ПОМІТНУ ФОРМУ — довгий ряд однакових літер у слові.
 *     Її ловить `REPEATED_LETTER` і не називає;
 *   - друга форми не має, тож від неї лишається лише ВІДБИТОК (sha256, перші
 *     16 знаків) від зведеного до нижнього регістру рядка. Відбиток не
 *     віддає назви назад, а порівнювати з ним можна.
 *
 * Межа названа вголос: відбиток ловить рівно ту саму послідовність слів.
 * Скорочення чи перестановка його оминуть. Це заслін від повернення того
 * самого рядка копіпастом, а не доказ відсутності будь-якої згадки.
 *
 * АБЕТКА — ЦЕ ТЕЖ ФОРМА ЗАПИСУ, І ВОНА ХОВАЛА РЯДОК ТАК САМО, ЯК NFD.
 *
 * До 2026-08-27 ряд шукали лише в кирилиці (`[\u0400-\u04FF]`). Та сама книжка
 * В ПЕРЕКЛАДІ має ТУ САМУ помітну форму, набрану ЛАТИНКОЮ, — і клас її не
 * бачив. Прогін воріт по всіх відстежуваних файлах знайшов п'ять таких рядків:
 * назву перекладеного видання (разом із прізвищем у ролі автора) в
 * `tests/unit/rules-en.test.ts` і транслітеровану назву першого видання в
 * `tests/unit/jsx-apply-logic.test.ts`. Рівно той клас, що й NFD вище: ворота
 * стерегли ФОРМУ, а інший запис тієї самої назви йшов повз них.
 *
 * ПОРІГ У ШІСТЬ ЛІТЕР НЕ БЕЗКОШТОВНИЙ, І ЦІНУ ЗМІРЯНО, А НЕ ПРИПУЩЕНО.
 *
 * На 607 прочитаних відстежуваних файлах він дає рівно два класи хибних
 * спрацювань, обидва названі поіменно нижче (`hexLiteral`, `upstreamHandle`).
 * Нижчий поріг коштує дорожче: п'ять однакових літер накривають ще й
 * `findOccurrences("ааааа", "аа")` у `tests/unit/matcher.test.ts` — законний
 * взірець алгоритму, а чотири додають `YYYY`, `XXXX` і `zzzz` із форматних
 * заповнювачів.
 *
 * МЕЖА ПОРОГУ, НАЗВАНА ВГОЛОС: транслітерація з П'ЯТЬМА однаковими літерами
 * під шість не підпадає. Саме такою була назва гілки в жорстко вписаних шляхах
 * `scripts/probe-*.mjs` — її прибрано руками, і ворота від її повернення НЕ
 * бережуть. Це свідомий обмін: поріг у п'ять зробив би хибним спрацюванням
 * законний взірець вище.
 */
const REPEATED_LETTER = /([A-Za-z\u0400-\u04FF])\1{5,}/u;
/* Той самий взірець із `g` — щоб судити про КОЖЕН ряд у рядку окремо. Окрема
 * стала, а не прапорець на тій самій: `lastIndex` у `.test()` — тихий стан. */
const REPEATED_LETTER_ALL = new RegExp(REPEATED_LETTER.source, "gu");
const DENIED_DIGESTS = new Set(["39dbd5cdbd9f1dad", "523ea99577b7411f"]);

function digest(s: string): string {
  return createHash("sha256").update(s.normalize("NFC").toLowerCase()).digest("hex").slice(0, 16);
}

/** Усі послідовності з 1–6 слів у рядку — щоб відбиток багатослівної назви мав із чим збігтися. */
function phrases(line: string): string[] {
  const words = line.match(/[\p{L}\p{N}][\p{L}\p{N}.'\u2019-]*/gu) ?? [];
  const out: string[] = [];
  for (let i = 0; i < words.length; i += 1) {
    for (let n = 1; n <= 6 && i + n <= words.length; n += 1) out.push(words.slice(i, i + n).join(" "));
  }
  return out;
}

/** Одна знахідка: чим саме рядок себе видав. */
export interface PrivateHit {
  what: string;
  text: string;
}

/**
 * Шість детекторів над ОДНИМ рядком. Порядок і формулювання причин збігаються
 * з тими, що ворота показували доти, — щоб повідомлення про падіння лишилося
 * впізнаваним.
 *
 * `file` потрібен рівно одному винятку (рядок авторського права в LICENSE) і
 * тому необов'язковий: у повідомленні коміта файла немає.
 */
export function detectPrivate(raw: string, file?: string): PrivateHit[] {
  const line = normalise(raw);
  const hits: PrivateHit[] = [];
  const at = (what: string) => hits.push({ what, text: line.trim().slice(0, 140) });

  /* 1. Домашня тека конкретної машини. */
  for (const m of line.matchAll(/\/Users\/[A-Za-z0-9._-]+/gu)) {
    if (!ALLOWED.placeholderHome.test(m[0])) at("абсолютний шлях у чиюсь домівку");
  }

  /* 2. Справжня поштова адреса. */
  for (const m of line.matchAll(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/gu)) {
    if (ALLOWED.exampleMailHosts.test(m[0])) continue;
    if (file !== undefined && ALLOWED.licenseCopyright(file)) continue;
    at("поштова адреса");
  }

  /* 3. ISBN конкретного видання. */
  for (const m of line.matchAll(/97[89][-\s‐‑–]\d[\d\s\-‐‑–]{7,}\d/gu)) {
    if (ALLOWED.dashesToHyphen(m[0]) !== ALLOWED.syntheticIsbn) at("ISBN видання");
  }

  /* 4. Тека хмарного диска, названа за поштою власника. */
  if (/GoogleDrive-(?!designer@example\.com)/u.test(line) && !ALLOWED.elidedDrive.test(line)) {
    at("шлях до чужого Google Drive");
  }

  /* 5. Назва видання за ФОРМОЮ — ряд однакових літер у будь-якій абетці. */
  for (const m of line.matchAll(REPEATED_LETTER_ALL)) {
    const token = tokenAt(line, m.index ?? 0);
    if (ALLOWED.hexLiteral.test(token)) continue;
    if (ALLOWED.upstreamHandle.has(token)) continue;
    at("схоже на назву конкретного видання");
    break;
  }

  /* 6. Назва видання за ВІДБИТКОМ. */
  for (const phrase of phrases(line)) {
    if (DENIED_DIGESTS.has(digest(phrase))) {
      at("назва конкретного видання (збіг за відбитком)");
      break;
    }
  }

  return hits;
}

export {
  ALLOWED,
  DENIED_DIGESTS,
  digest,
  normalise,
  phrases,
  REPEATED_LETTER,
  REPEATED_LETTER_ALL,
  tokenAt,
};
