import { describe, expect, it } from "vitest";
import { isProtected } from "../../src/bibliography/nobreak.js";
import { NBSP } from "../../src/bibliography/chars.js";

describe("isProtected", () => {
  it("символ U+00A0 сам по собі захищає", () => {
    const t = `А.${NBSP}В.`;
    expect(isProtected(t, 2, 3, false)).toBe(true);
  });

  it("атрибут noBreak сам по собі захищає, попри звичайний пробіл", () => {
    /*
     * Спек §0.5: захист буває GREP-стилем із No Break. Детектор, що дивиться
     * лише на символи, на такому виданні дасть тисячі хибних спрацювань.
     */
    expect(isProtected("А. В.", 2, 3, true)).toBe(true);
  });

  it("звичайний пробіл без атрибута — не захищено", () => {
    expect(isProtected("А. В.", 2, 3, false)).toBe(false);
  });
});

/*
 * ЗАХИСТОМ Є БУДЬ-ЯКИЙ НЕРОЗРИВНИЙ ПРОБІЛ, А НЕ ЛИШЕ U+00A0.
 *
 * U+202F (вузький нерозривний) і U+2007 (цифровий) не дають перенесення так
 * само. Зараховувався лише U+00A0, тож роздільник, набраний вузьким
 * нерозривним — звичайна річ у наборі з тонкими пробілами коло ініціалів, —
 * звітувався як НЕЗАХИЩЕНИЙ, ще й з упевненістю high.
 */
describe("інші нерозривні пробіли", () => {
  it.each([
    ["U+202F вузький нерозривний", "\u202f"],
    ["U+2007 цифровий", "\u2007"],
  ])("%s теж захищає", (_name, ch) => {
    expect(isProtected(`А.${ch}В.`, 2, 3, false)).toBe(true);
  });

  it("НЕГАТИВНИЙ КОНТРОЛЬ: звичайний пробіл не захищає", () => {
    /* Інакше правка звела б родину bib-nbsp-* до мовчання. */
    expect(isProtected("А. В.", 2, 3, false)).toBe(false);
  });

  it("НЕГАТИВНИЙ КОНТРОЛЬ: U+2011 (нерозривний дефіс) — не пробіл", () => {
    expect(isProtected("А.\u2011В.", 2, 3, false)).toBe(false);
  });
});
