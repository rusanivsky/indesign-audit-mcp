import type { CharMeasure, LineMeasure } from "../../../src/composition/types.js";

/** Ширина літери у фікстурі, пункти. Слово «аб» — це рівно 2 × LETTER. */
const LETTER = 5;

/**
 * Спільний конструктор рядка для Задач 7–11 і 13. Дублювати його по файлах
 * не можна: дві копії розійдуться, і тести почнуть міряти різні речі.
 *
 * За замовчуванням будує «аб вг» із заданою шириною пробілу: придатний до
 * виміру, виключений, явно коротший за міру (200 пт), кегль 10.
 * Решта опцій відтворює виміряні на книжці пастки — див. коментарі до полів.
 */
export function line(opts: {
  spaceWidth: number;
  isLast: boolean;
  style?: string;
  /** `null` — мішаний кегль у межах абзацу, як його віддає InDesign. */
  size?: number | null;
  words?: number;
  /**
   * Літери одного слова. За замовчуванням «аб» — рівно 2 × LETTER.
   *
   * Потрібне Задачі 9: правило «кінцевий рядок — одне коротке слово» міряє
   * ДОВЖИНУ слова, а з незмінним «аб» кожне слово має рівно 2 символи й поріг
   * не можна перетнути в жоден бік. Ширина слова лишається зв'язаною з його
   * довжиною (кожен гліф — LETTER), як і в справжньому наборі.
   *
   * Керівні символи C0 (`charCodeAt < 32`) кладуться сюди як `ch: null` з
   * нульовим просуванням — саме так їх віддає шар виміру (`isPrintableChar`), і
   * саме так у книжці поводяться якір таблиці U+0016 та маркер виноски U+0004.
   */
  word?: string;
  /**
   * Просування, яке дістає керівний символ C0, пункти. За замовчуванням 0.
   *
   * Виміряно ще у Фазі 2: InDesign дає керівним символам кінця рядка/абзацу
   * СИНТЕТИЧНУ ширину 3,21994018554688 пт (`docs/measured-facts-phase3.md`,
   * розділ про гіпотезу H1) — тобто нуль тут є спрощенням фікстури, а не
   * властивістю даних. Задачі 11 воно потрібне, щоб перевірити правило «пробіл
   * без ДРУКОВАНОГО правого сусіда не рахується»: при нульовому просуванні таке
   * правило не відрізнити від фільтра `width > 0`, бо обидва відкидають той
   * самий проміжок.
   */
  controlWidth?: number;
  /**
   * Явний перелік слів рядка — коли слова мають бути РІЗНІ.
   *
   * Потрібне Задачі 10: правила переносу читають ОСТАННЄ слово рядка й ПЕРШЕ
   * слово наступного, тож фікстура з однакових «аб» не може відрізнити хвіст
   * від голови. Перекриває `words`/`word`; ширина кожного гліфа лишається
   * LETTER, як і скрізь у цьому конструкторі, тож геометрія й текст не
   * розходяться (саме через це тут окрема опція, а не сире перекриття `text`).
   */
  wordList?: string[];
  /**
   * Явні КООРДИНАТИ міжслівних проміжків, пункти (за зростанням).
   *
   * Потрібне Задачі 11: коридор міряє не ширину пробілу, а те, чи проміжки
   * сусідніх рядків перекриваються по горизонталі, тобто фікстура мусить
   * задавати саме x проміжку, а не кількість слів. Після кожного пробілу
   * ставиться друкований сусід — пробіл без нього не рахується ні
   * калібруванням, ні детектором коридорів (`spaceGaps`), тож без сусіда
   * фікстура міряла б неіснуючу річ.
   *
   * Перекриває `wordList`/`words`/`word`. Ширина кожного проміжку — `spaceWidth`,
   * ширина гліфа — LETTER, як і скрізь у цьому конструкторі, тож геометрія й
   * текст не розходяться (`chars.length === text.length`) — саме через це тут
   * окрема опція, а не сире перекриття `chars`.
   */
  gapsAt?: number[];
  /** Ефективна міра абзацу. За замовчуванням 200 — рядок явно недобирає. */
  columnWidth?: number;
  /**
   * Рядок дотягує до міри: ефективна міра дорівнює його ширині по правому
   * краю останнього НЕпробільного гліфа. Так поводяться забруднені останні
   * рядки абзаців 86 і 130 — фактично виключені попри LEFT_JUSTIFIED.
   */
  fillsMeasure?: boolean;
  /** Рядок ширший за міру на стільки пунктів (абзац 130: 0,2505 пт). */
  overshoot?: number;
  /** Кінцевий пробіл, що законно звисає за міру, пункти (до 4,599 пт). */
  trailingSpace?: number;
  /**
   * Рядок закінчується знаком кінця абзацу `\r` — тобто це ОСТАННІЙ рядок
   * абзацу так, як його віддає InDesign: `line.contents` останнього рядка
   * містить `\r`, у `chars` він приходить як `ch: null` (`types.ts`, коментар
   * до `CharMeasure.ch`; той самий поділ, що й у `isPrintableChar` шару виміру).
   *
   * Потрібне Задачі 13: щоб адресувати правку в тексті КОНТЕЙНЕРА, пропозиція
   * зшиває тексти рядків абзацу й звіряє результат із `ContainerSnapshot.text`,
   * де абзаци розділені саме `\r`. Без цієї опції фікстура з двох абзаців
   * розходилася б зі знімком на один символ на кожній межі, і перевірити
   * арифметику зсувів було б нічим.
   *
   * Просування дістає `controlWidth` (типово 0), як і решта керівних символів.
   */
  endsParagraph?: boolean;
  /**
   * Рядок закінчується літеральним дефісом — гліф уже в координатах тексту.
   * Його ширина (2,8 пт при кеглі 10 = 0,28 кегля) навмисно НЕ дорівнює
   * запасному HYPHEN_EM_FALLBACK = 0,34: інакше жоден тест не відрізнив би
   * виведене з даних значення від запасного.
   */
  literalHyphen?: boolean;
  /**
   * Рядок закінчується м'яким переносом U+00AD. На розриві він МАЛЮЄТЬСЯ, тобто
   * уже входить у `right`, — але як зразок ширини непридатний (поза розривом
   * його гліфова ширина нульова). Тому він не є ні джерелом виміру, ні
   * кандидатом на допуск.
   */
  softHyphen?: boolean;
  /** Перенос, намальований композитором: його НЕМАЄ ні в text, ні в right. */
  endsWithHyphen?: boolean;
  /** Порожній абзац: жодного гліфа, повна columnWidth при ширині 2,3–7,6 пт. */
  empty?: boolean;
  /** Рамка повернута на ±90°: left === right, усі x однакові (виміряний випадок). */
  rotated?: boolean;
  /**
   * Довільний кут повороту. `rotated` — це `rotationAngle !== 0`, а не «±90°»,
   * тож рамка під кутом 30° теж непридатна — але її осеорієнтовані x
   * ВАРІЮЮТЬСЯ, і фільтр `w > 0` такий рядок не ловить. Саме на ньому видно,
   * що правило придатності робить свою роботу, а не дублює інший фільтр.
   */
  rotationAngle?: number;
  justification?: string;
  /**
   * Межі виключки стилю. `null` у полі — мішане значення в межах абзацу, як
   * його віддає InDesign: межі НЕ виміряні, а не «немає межі».
   */
  spacing?: LineMeasure["spacing"];
  /* ——— адреса рядка; потрібна там, де знахідок більше однієї ——— */
  containerId?: string;
  page?: string;
  spreadIndex?: number;
  paragraphIndex?: number;
  /**
   * Базова лінія рядка, пункти. За замовчуванням 100 для всіх рядків — доти
   * жоден детектор її не читав.
   *
   * Потрібне Задачі 11: коридор існує лише між рядками, що СТОЯТЬ ОДИН ПІД
   * ОДНИМ, а єдина ознака цього в `LineMeasure` — зростання `baseline`
   * (y в InDesign росте вниз). Спадання означає перехід у наступну колонку
   * багатоколонкового фрейму, тобто рядки не сусідні.
   */
  baseline?: number;
  /** Перекриває позицію, виведену з `isLast`. */
  lineInParagraph?: number;
  paragraphLineCount?: number;
  /**
   * Межа ФРЕЙМУ, а не сторінки. Виміряно: 620 фреймів, у кожному рівно один
   * перший і один останній рядок; щонайменше 32 абзаци книжки лежать одразу у
   * двох фреймах (вимір рахував абзаци на різних СТОРІНКАХ — фреймовий розрив
   * є їх надмножиною). Саме на цих прапорцях тримаються вісяки й сироти.
   */
  isFirstInFrame?: boolean;
  isLastInFrame?: boolean;
  /**
   * Рядок лежить на майстер-сторінці. За замовчуванням `false` — доти поле
   * було в типі `LineMeasure`, але сюди, у конструктор, не діставалось, тож
   * жоден виклик не міг зібрати фікстуру з `isMaster: true` через опції;
   * доводилось перекривати поле сирим спредом ПІСЛЯ виклику. Задачі 10 Фази 4
   * потрібно саме опцією: чотири детектори композиції отримують власний
   * `includeMasters`, і їхні тести звіряють рядок майстра, зібраний рівно так
   * само, як звичайний.
   */
  isMaster?: boolean;
}): LineMeasure {
  const chars: CharMeasure[] = [];
  let x = 0;
  let text = "";

  if (opts.empty) {
    /* Порожній абзац: сам лише керівний символ, власна ширина ~2,3 пт. */
    chars.push({ x: 0, ch: null });
    text = "\r";
    x = 2.3;
  } else if (opts.gapsAt !== undefined) {
    /* Проміжок у заданому x і друкований сусід одразу за ним. */
    for (const gx of opts.gapsAt) {
      chars.push({ x: gx, ch: " " });
      text += " ";
      chars.push({ x: gx + opts.spaceWidth, ch: "а" });
      text += "а";
      x = gx + opts.spaceWidth + LETTER;
    }
  } else {
    const list = opts.wordList ?? new Array(opts.words ?? 2).fill(opts.word ?? "аб");
    for (let w = 0; w < list.length; w++) {
      if (w > 0) {
        chars.push({ x, ch: " " });
        text += " ";
        x += opts.spaceWidth;
      }
      for (const ch of list[w]!) {
        /* Той самий поділ, що й у шарі виміру: C0 — «не гліф», у `text` він
         * лишається справжнім символом, у `chars` стає `ch: null`. */
        const printable = ch.charCodeAt(0) >= 32;
        chars.push({ x, ch: printable ? ch : null });
        text += ch;
        x += printable ? LETTER : (opts.controlWidth ?? 0);
      }
    }
    if (opts.literalHyphen || opts.softHyphen) {
      const ch = opts.softHyphen ? "\u00AD" : "-";
      chars.push({ x, ch });
      text += ch;
      x += 0.28 * (opts.size === undefined ? 10 : (opts.size ?? 10));
    }
  }

  /* Правий край останнього гліфа — те, з чим порівнюється міра. */
  const glyphRight = x;

  if (opts.trailingSpace !== undefined) {
    chars.push({ x, ch: " " });
    text += " ";
    x += opts.trailingSpace;
  }

  /* Знак кінця абзацу йде НАЙОСТАННІШИМ — після кінцевого пробілу, як у
   * справжньому `line.contents`. */
  if (opts.endsParagraph) {
    chars.push({ x, ch: null });
    text += "\r";
    x += opts.controlWidth ?? 0;
  }

  const columnWidth =
    opts.fillsMeasure || opts.overshoot !== undefined
      ? glyphRight - (opts.overshoot ?? 0)
      : (opts.columnWidth ?? 200);

  const squashed = opts.rotated ?? false;
  const rotationAngle = opts.rotationAngle ?? (squashed ? -90 : 0);
  const rotated = squashed || rotationAngle !== 0;
  if (squashed) {
    /* Виміряний випадок ±90°: усі координати збігаються, ширина нульова. */
    for (const c of chars) c.x = 0;
  }

  return {
    containerId: opts.containerId ?? "story:0",
    page: opts.page ?? "1",
    /* Замовчування — розворот, виведений з номера сторінки, щоб наявні
     * фікстури поводилися як досі: сусідні сторінки в них означали різні
     * розвороти. Тест шва задає його явно. */
    spreadIndex: opts.spreadIndex ?? (Number(opts.page ?? "1") || 0),
    paragraphIndex: opts.paragraphIndex ?? 0,
    lineInParagraph: opts.lineInParagraph ?? (opts.isLast ? 1 : 0),
    paragraphLineCount: opts.paragraphLineCount ?? 2,
    left: 0,
    right: squashed ? 0 : x,
    baseline: opts.baseline ?? 100,
    columnWidth,
    styleName: opts.style ?? "Основний текст",
    pointSize: opts.size === undefined ? 10 : opts.size,
    spacing: opts.spacing ?? { min: 80, desired: 100, max: 133 },
    justification: opts.justification ?? "LEFT_JUSTIFIED",
    text,
    chars,
    endsWithHyphen: opts.endsWithHyphen ?? opts.literalHyphen ?? opts.softHyphen ?? false,
    isFirstInFrame: opts.isFirstInFrame ?? false,
    isLastInFrame: opts.isLastInFrame ?? false,
    rotated,
    rotationAngle,
    isMaster: opts.isMaster ?? false,
  };
}
