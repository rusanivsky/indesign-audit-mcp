import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { jsxModules } from "../../src/bridge/runner.js";

const RAW = readFileSync("src/jsx/pagination.jsx", "utf8");
const TOPOLOGY_RAW = readFileSync("src/pagination/topology.ts", "utf8");

/*
 * Ґарди дивляться на КОД, не на коментарі.
 *
 * Перша редакція цього файла впала на власному коментарі, який згадував
 * `page.textFrames` у поясненні, ЧОМУ його не використовують. Ґард, що не
 * відрізняє код від тексту про код, дає хибне спрацювання рівно там, де
 * автор постарався пояснити рішення, — тобто карає за документування.
 */
const SRC = RAW.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
const TOPOLOGY = TOPOLOGY_RAW.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");

/**
 * Чотири нерівності предиката перекриття, зведені до спільної форми.
 *
 * Ім'я допуску навмисно стирається (`eps` у JSX проти `epsilon` у TS): звіряти
 * треба ФОРМУ порівнянь і порядок осей, а не те, як названо змінну. Значення
 * самого допуску звіряється окремо — саме воно, а не ім'я, вирішує відповідь.
 */
function overlapConditions(src: string, marker: string): string[] {
  const at = src.indexOf(marker);
  if (at < 0) throw new Error(`У джерелі немає «${marker}» — предикат перейменували або зняли.`);
  const body = src.slice(at, src.indexOf("return true;", at));
  return [...body.matchAll(/if \(([ab]\.[xy][12]) < ([ab]\.[xy][12]) - \w+\) return false;/g)].map(
    (m) => `${m[1]} < ${m[2]} - E`,
  );
}

/** Число допуску з оголошення константи — з КОДУ, а не з пам'яті тесту. */
function epsilonOf(src: string, declaration: RegExp): string {
  const m = declaration.exec(src);
  if (m === null) throw new Error(`Не знайдено оголошення допуску: ${String(declaration)}`);
  return m[1]!;
}

/*
 * ПАРИТЕТ ДВІЙНИКІВ, ЯКИЙ ДОТИ ТРИМАВСЯ ЛИШЕ КОМЕНТАРЕМ.
 *
 * Борг Задачі 5, знахідка I2 рецензії `0abf0be`. `rectsOverlap`
 * (`src/pagination/topology.ts`) — свідомий двійник `IDMCP.boundsTouch`
 * (`src/jsx/pagination.jsx`), і коментар при константі обіцяє, що значення
 * «мусить лишатись тим самим». Але не падало НІЩО, якби одна з двох констант
 * змінилась або форму умови в JSX переписали: обидва набори тестів лишились би
 * зеленими, а чистий TypeScript і вимір почали б відповідати про перекриття
 * по-різному. `ClaimFrame.overlaps` будує ВИКЛЮЧНО `IDMCP.boundsTouch`, тож
 * розбіжність означала б, що детектор §4.9 міркує про топологію, якої вимір не
 * бачив.
 *
 * Спільного дому в цих двох реалізацій немає й бути не може: JSX працює в ES3
 * без модулів і імпортувати константу не може. Тому паритет перевіряється
 * єдиним доступним способом — читанням обох джерел як тексту, тією самою
 * ідіомою, що й решта ґардів цього файла.
 */
describe("rectsOverlap ↔ IDMCP.boundsTouch — двійники, а не однойменні функції", () => {
  it("чотири нерівності збігаються формою й порядком осей", () => {
    const jsx = overlapConditions(SRC, "IDMCP.boundsTouch = function");
    const ts = overlapConditions(TOPOLOGY, "export function rectsOverlap");
    /* Чотири, а не «скільки знайшлось»: зникла умова — теж розбіжність, і
     * порожні масиви зійшлися б між собою мовчки. */
    expect(jsx).toHaveLength(4);
    expect(ts).toEqual(jsx);
  });

  it("допуск — те саме число в обох джерелах", () => {
    /*
     * Порівнюються ДВА ДЖЕРЕЛА між собою, а не кожне з літералом у тесті.
     * Свідома зміна допуску під інше видання лишиться зеленою, якщо її
     * зробити в обох місцях; зміна в одному — впаде. Літерал тут був би
     * третьою копією тієї самої константи, тобто ще одним місцем, де
     * розходження стає можливим.
     */
    const jsx = epsilonOf(SRC, /IDMCP\.BOUNDS_EPSILON_MM = ([\d.]+);/);
    const ts = epsilonOf(TOPOLOGY, /export const BOUNDS_EPSILON_MM = ([\d.]+);/);
    expect(ts).toBe(jsx);
  });
});

describe("pagination.jsx", () => {
  it("модуль зареєстровано, інакше обробник не існує в рантаймі", () => {
    expect(jsxModules({})).toContain("pagination.jsx");
  });

  it("порівнює маркер ІДЕНТИЧНІСТЮ, а не через String()", () => {
    /* String(ch.contents) для автомаркера дає рядок "AUTO_PAGE_NUMBER" —
     * виміряно Фазою 4. Порівняння через String випадково працює для одного
     * маркера й тихо ламається на інших. */
    expect(SRC).toMatch(/ch\.contents === list\[i\]\[1\]/);
    expect(SRC).not.toMatch(/String\(\s*ch\.contents\s*\)\s*===/);
  });

  it("обходить allPageItems, а НЕ page.textFrames", () => {
    /* Виміряно зондом H6: page.textFrames не бачить прив'язаних рамок —
     * на с.8 реальної книжки 1 проти 9. Прохід на ньому доповів би
     * «знахідок немає», тобто мовчазну сліпоту. */
    expect(SRC).toMatch(/page\.allPageItems/);
    expect(SRC).not.toMatch(/page\.textFrames/);
  });

  it("дістає ТРЕТЄ джерело рамок — page.masterPageItems", () => {
    /*
     * ДРУГЕ, ОКРЕМЕ сліпе місце, і плутати його з першим не можна:
     * прив'язані рамки `allPageItems` БАЧИТЬ, а непереозначений елемент
     * батьківської сторінки не видно НІ там, НІ в `page.textFrames`.
     * Виміряно зондом H7 (Питання 1 і 6): на с.19 книжки `allPageItems`
     * повернув 1 при `masterPageItems: 1`, і під цією сліпотою лежали
     * 40 парних сторінок, усі колонтитули й три батьківські автоматичні
     * колонцифри.
     *
     * Ґард дешевий і НЕ потребує InDesign — а це важливо саме тут: зняти
     * третє джерело можна одним рядком, і жоден юніт-тест цього не побачив би.
     * Інтеграційне покриття існує (фікстура має батьківські рамки з
     * Задачі 3F), але воно платне й іде на живому застосунку.
     */
    expect(SRC).toMatch(/page\.masterPageItems/);
  });

  it("нема від чого звести майстрові межі — це null, а не тихий нульовий зсув", () => {
    /*
     * ДВІ РІЗНІ ПРИЧИНИ НЕ СМІЮТЬ ЗЛИВАТИСЬ У МОВЧАЗНУ ГІЛКУ: «майстрової
     * сторінки в елемента немає» і «`page.bounds` документної сторінки не
     * прочитався». Доти обидві давали `dy = dx = 0`, тобто СИРІ майстрові
     * координати під виглядом документних — зсув на цілу ширину сторінки
     * (215,9 мм, вимір Питання 17), рамка за межами власного розвороту, нуль
     * перекриттів і «сплячих дублів немає» там, де вони є.
     *
     * ЧИМ САМЕ ПЕРША ПРИЧИНА ВМИКАЄТЬСЯ — ВИМІРЯНО, і попередня редакція цього
     * коментаря називала не те. Тут стояло «елемент перетинає корінець
     * майстра»; зонд на фікстурі показав, що така рамка має `parentPage` = «A»,
     * тобто гілки НЕ вмикає. Вмикає її ЛИСТ ГРУПИ, що лежить за межами
     * майстрових сторінок: сама група майстровій сторінці приписана й у
     * `page.masterPageItems` приходить, а її лист — уже нікому.
     *
     * Стан тепер покритий фікстурою (`master-group-leaf-outside-pages`), тож
     * цей ґард більше не єдине, що тримає гілку, — але лишається, бо він
     * дешевий і не потребує InDesign.
     */
    expect(SRC).toMatch(/if \(origin === null \|\| pageOrigin === null\) return null;/);
    expect(SRC).not.toMatch(/var dy = 0;/);
  });

  it("невідомі межі не підмінюються нуль-прямокутником", () => {
    /*
     * Нуль-прямокутник — теж ПРЯМОКУТНИК: він відповідає на питання «де
     * рамка» числами, яких ніхто не міряв, і детектор §4.9 дістав би відповідь
     * замість відмови. Поведінка покрита інтеграційно (стан
     * `master-group-leaf-outside-pages`), але цей ґард ловить саме ПОВЕРНЕННЯ
     * підміни — рядок, який легко дописати назад «щоб схема не падала».
     */
    expect(SRC).not.toMatch(/y1: 0, x1: 0, y2: 0, x2: 0/);
  });

  it("ключі-рядки з документа шукаються як ВЛАСНІ, а не через прототип", () => {
    /*
     * Назви стилів — довільні рядки користувача. `{}["constructor"]` віддає
     * функцію замість `undefined`, і на цьому падав увесь вимір (`TypeError …
     * reading 'frames'`). Поведінка покрита інтеграційно (стиль на ім'я
     * `constructor` у фікстурі), ґард тримає ФОРМУ: жодного індексного
     * читання цих двох словників без `hasOwn`.
     */
    expect(SRC).toMatch(/IDMCP\.hasOwn = function/);
    expect(SRC).toMatch(/IDMCP\.hasOwn\(masterSkippedAt, styleName\)/);
    expect(SRC).not.toMatch(/var skipAt = masterSkippedAt\[styleName\];/);
    expect(SRC).not.toMatch(/var role = declared\[styleName\];/);
    /*
     * Четверте місце того самого класу — поабзацний цикл заголовків ТІЛА. Він
     * лишався поза зачисткою до цього коміту: шкоди від нього немає (значення
     * з прототипу — функція, а вона ніколи не дорівнює рядковому літералу),
     * але саме він був єдиною уцілілою формою, доступною для копіювання, а
     * ґард перелічує форми поіменно й цієї не називав.
     */
    expect(SRC).toMatch(/IDMCP\.hasOwn\(declared, pStyle\)/);
    /* Заборонена саме ЗЛИТА форма: `declared[pStyle] !== "heading"` сам по
     * собі лишається в коді рядком нижче — але вже ПІСЛЯ `hasOwn`. */
    expect(SRC).not.toMatch(/pStyle === null \|\| declared\[pStyle\]/);
  });

  it("майстрова рамка не доходить до ПОАБЗАЦНОГО збору заголовків", () => {
    /*
     * Гейт вище відкидає майстрову рамку за РОЛЛЮ, тобто колонцифру пропускає
     * далі — а цикл заголовків поабзацний і `fromMaster` не перевіряв узагалі.
     * Виміряно: 5 фантомних заголовків з одного об'єкта (рецензія `49faac5`).
     * Поведінка покрита інтеграційно; ґард стоїть тому, що рядок — один, і
     * зняти його можна не помітивши.
     */
    expect(SRC).toMatch(/if \(rec\.fromMaster === true\) continue;\s*\n\s*if \(!wantsHeadings\) continue;/);
  });

  it("бере стилі з allParagraphStyles — звичайна колекція не бачить груп", () => {
    expect(SRC).toMatch(/doc\.allParagraphStyles/);
  });

  it("не використовує вкладених тернарників", () => {
    /* 2026-08-04 такий вираз мовчки повернув не ту гілку, і з логу цього не
     * було видно. */
    expect(SRC).not.toMatch(/\?[^;{}\n]*\?[^;{}\n]*:[^;{}\n]*:/);
  });

  it("відновлює одиниці виміру у finally", () => {
    expect(SRC).toMatch(/finally\s*\{[\s\S]*measurementUnit = previousUnit/);
  });
});
