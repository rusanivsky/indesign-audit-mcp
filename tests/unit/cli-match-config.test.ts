import { describe, expect, it } from "vitest";
import { зіставитиКонфіг } from "../../src/cli/audit.js";

const конфіги = [
  { шлях: "/к/example-textbook.json", назва: "Приклад", docPath: "02 Приклад підручника.indd" },
  { шлях: "/к/example-book.json", назва: "Book", docPath: "/Drive/книжки/Book 260817.indd" },
];

describe("зіставлення відкритого документа з конфігом", () => {
  it("збережений документ — за ПОВНИМ шляхом (тотожність це шлях, R10/R23)", () => {
    const r = зіставитиКонфіг(конфіги, "Book 260817.indd", "/Drive/книжки/Book 260817.indd");
    expect(r?.шлях).toBe("/к/example-book.json");
  });

  /*
   * Незбережений документ шляху не має, тож лишається ім'я — і саме тут
   * жила пастка: InDesign віддає його в NFD, конфіг написано в NFC.
   */
  it("незбережений — за іменем, і форма Unicode зводиться", () => {
    const r = зіставитиКонфіг(конфіги, "02 Приклад підручника.indd", "");
    expect(r?.шлях).toBe("/к/example-textbook.json");
  });

  it("шлях виграє в імені: два конфіги з однаковим іменем файлу не плутаються", () => {
    const два = [
      { шлях: "/к/а.json", назва: "А", docPath: "/один/книга.indd" },
      { шлях: "/к/б.json", назва: "Б", docPath: "/інший/книга.indd" },
    ];
    expect(зіставитиКонфіг(два, "книга.indd", "/інший/книга.indd")?.шлях).toBe("/к/б.json");
  });

  it("немає конфіга — null, а не перший-ліпший", () => {
    expect(зіставитиКонфіг(конфіги, "чужа.indd", "/десь/чужа.indd")).toBeNull();
  });
});
