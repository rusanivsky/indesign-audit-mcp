import { describe, expect, it } from "vitest";
import { detectBleedShort, detectOffPage } from "../../src/geometry/frame.js";
import type { ItemMeasure, PageMeasure } from "../../src/geometry/types.js";

function page(side: "left" | "right" = "left"): PageMeasure {
  return {
    name: "96", side, width: 538.582677165354, height: 623.622047244095,
    margins: { top: 51, bottom: 60, inside: 90, outside: 79, columnCount: 1, columnGutter: 12 },
    bleed: { top: 8.50393700787402, bottom: 8.50393700787402, inside: 0, outside: 8.50393700787402 },
  };
}

function item(bounds: [number, number, number, number]): ItemMeasure {
  return {
    itemId: 1, page: "96", side: "left", type: "Rectangle", parentKind: "Spread",
    anchored: false, inGroup: false, layer: "Шар 1", layerVisible: true,
    layerPrintable: true, locked: false, rotation: 0,
    bounds, wrapMode: null, wrapOffsets: null, anchorStyle: null, graphic: null,
  };
}

/**
 * Асиметрична сторінка: top/bottom/inside/outside вильоту — ЧОТИРИ РІЗНІ
 * значення. `page()` вище (усі три виміряні боки рівні 8.50393700787402) не
 * годиться для ізоляції однієї сторони: обмін індексів верх↔ліво чи
 * inside↔outside лишився б непоміченим, бо різниця однаково мала б бути
 * малою. Тут будь-яка плутанина сторони чи індексу дає числове неспівпадіння.
 */
function asymmetricPage(side: "left" | "right"): PageMeasure {
  return {
    name: "96", side, width: 400, height: 600,
    margins: { top: 51, bottom: 60, inside: 90, outside: 79, columnCount: 1, columnGutter: 12 },
    bleed: { top: 4, bottom: 9, inside: 2, outside: 13 },
  };
}

describe("detectOffPage", () => {
  it("повнополосна плашка РІВНО у виліт знахідкою не є", () => {
    /* Виміряний елемент с. 96 робочої книжки: [−8.50, −8.50, 632.13, 538.58]
     * при вильоті 8.50393700787402. Еталон береться з документа, тож він
     * мовчить. */
    expect(detectOffPage([item([-8.5, -8.5, 632.126, 538.582677165354])], [page()])).toHaveLength(0);
  });

  it("знаходить елемент, що вийшов за виліт", () => {
    const found = detectOffPage([item([-20, -8.5, 632.126, 538.58])], [page()]);
    expect(found).toHaveLength(1);
    expect(found[0]!.defect).toBe("frame-off-page");
  });

  it("зсередини виліт нульовий — вихід за корінець є знахідкою", () => {
    /* На verso внутрішній край — праворуч (x = width). Виліт зсередини 0,
     * тож будь-який перехід за нього значущий. */
    const found = detectOffPage([item([100, 100, 200, 545])], [page("left")]);
    expect(found).toHaveLength(1);
  });

  it("елемент усередині аркуша знахідкою не є", () => {
    expect(detectOffPage([item([100, 100, 200, 300])], [page()])).toHaveLength(0);
  });

  it("виходить за виліт ВИКЛЮЧНО знизу — інші три боки з запасом усередині", () => {
    /* Recto (side="right"): для верху/низу сторона аркуша значення не міняє
     * (top/bottom не залежать від inside/outside), тож recto тут довільний;
     * навмисно взятий іншим за наступний тест, аби обидва боки мапінгу
     * inside/outside↔left/right отримали окремий прогін по всій родині
     * тестів. box = bleedBox = [-4, -2, 609, 413]. Верх (50), ліво (50) і
     * право (300) — глибоко всередині вильоту; тільки низ (629) виходить за
     * 609 рівно на 20 pt. Якби формула не рахувала низ узагалі (або рахувала
     * не той індекс), `over` вийшов би від'ємним і знахідки не було б. */
    const p = asymmetricPage("right");
    const found = detectOffPage([item([50, 50, 629, 300])], [p]);
    expect(found).toHaveLength(1);
    expect(found[0]!.value).toBe("20.00 pt");
  });

  /*
   * СТОРОЖ РІШЕННЯ I3 (рецензія хвилі виправлень, 2026-08-15).
   *
   * Гейт `rotation !== 0` стоїть у detectNearMiss і НЕ стоїть тут — і це
   * вибір, який доти не тримало ніщо, крім коментаря: мутант «додати
   * `if (item.rotation !== 0) continue;` у detectOffPage» проходив увесь
   * набір зелено. Без цих двох тестів перший же наступний рецензент
   * «вирівняє» детектори між собою — і 91 повернена рамка книжки мовчки
   * випаде з вироку про вихід за виліт.
   *
   * Підстава вибору — ВИМІР, а не смак (2026-08-15): прямокутник 300×40,
   * повернутий на 45°, дає geometricBounds 240,4163×240,4163 = (300+40)/√2,
   * і рівно visibleBounds. Отже габарит — ЩІЛЬНА осеорієнтована оболонка
   * повернутої фігури, а щільна оболонка перетинає межу вильоту тоді й лише
   * тоді, коли за неї виходить якийсь кут самої рамки. Для ВИРОКУ ПРО ВИХІД
   * це точний прилад; непридатний він лише для вироку про ВИРІВНЮВАННЯ, де
   * важать самі сторони, а не оболонка.
   */
  it("СТОРОЖ I3: повернена рамка, що вийшла за виліт, У ЗНАХІДКАХ — гейта тут бути не сміє", () => {
    const rotated = { ...item([-20, -8.5, 632.126, 538.58]), rotation: -90 };
    const found = detectOffPage([rotated], [page()]);
    expect(found).toHaveLength(1);
    expect(found[0]!.defect).toBe("frame-off-page");
  });

  it("СТОРОЖ I3: повернена рамка ВСЕРЕДИНІ вильоту знахідкою не стає", () => {
    /* Позитивний близнюк: попередній тест мусить доводити, що судиться
     * ГЕОМЕТРІЯ, а не сам факт повороту. Інакше він проходив би й на коді,
     * який оголошує знахідкою кожну повернену рамку. */
    const rotated = { ...item([-8.5, -8.5, 632.126, 538.582677165354]), rotation: -90 };
    expect(detectOffPage([rotated], [page()])).toHaveLength(0);
  });

  it("виходить за виліт ВИКЛЮЧНО ліворуч — інші три боки з запасом усередині", () => {
    /* Verso (side="left"): зовнішній край — зліва, тож лівий виліт бере
     * `bleed.outside` (13), а не `bleed.inside` (2) — саме мапінг, який
     * обмін inside/outside чи верх/ліво зламав би непомітно на симетричній
     * фікстурі. box = bleedBox = [-4, -13, 609, 402]. Верх (50), низ (300) і
     * право (200) — глибоко всередині; тільки ліво (-38) виходить за -13
     * рівно на 25 pt. Якби формула не рахувала ліво узагалі (або плутала
     * його з верхом), `over` вийшов би від'ємним і знахідки не було б. */
    const p = asymmetricPage("left");
    const found = detectOffPage([item([50, -38, 300, 200])], [p]);
    expect(found).toHaveLength(1);
    expect(found[0]!.value).toBe("25.00 pt");
  });
});

/**
 * ВКЛАДЕНИЙ ВМІСТ СУДИТИСЯ ЗА ВЛАСНИМ ГАБАРИТОМ НЕ МОЖЕ.
 *
 * ВИМІРЯНО НА КНИЖЦІ 2026-08-16: `page.allPageItems` віддає вкладене
 * зображення ОКРЕМИМ елементом поруч із рамкою, що його тримає —
 * «Image ← Rectangle» × 4 і «PDF ← Rectangle» × 2 на всю книжку. Габарит
 * такого елемента — НЕОБРІЗАНИЙ оригінал; рамка його кадрує, і на аркуш
 * потрапляє лише те, що всередині рамки.
 *
 * Ціна помилки: чотири зображення (с. 2, 20, 96, 128) діставали
 * `frame-off-page` на 34–74 pt, хоча їхні РАМКИ лежать точно на межі вильоту.
 * Знахідка відправляла оператора з'ясовувати неіснуючу проблему з друкарнею.
 *
 * Групи не кадрують — «TextFrame ← Group» (38 у книжці) лишається в популяції.
 */
function nested(bounds: [number, number, number, number], parentKind: string): ItemMeasure {
  return { ...item(bounds), type: "Image", parentKind };
}

describe("detectOffPage: вкладений вміст", () => {
  /* Необрізаний PSD ширший за свою рамку на 34.6 pt ліворуч — реальні числа с. 2. */
  const OVERSIZE: [number, number, number, number] = [-8.5, -43.2, 632.126, 573.2];

  it("зображення всередині рамки знахідки НЕ дає", () => {
    expect(detectOffPage([nested(OVERSIZE, "Rectangle")], [page()])).toHaveLength(0);
  });

  it("PDF усередині рамки — так само", () => {
    expect(detectOffPage([nested(OVERSIZE, "Rectangle")], [page()])).toHaveLength(0);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: той самий габарит НА РОЗВОРОТІ знахідку дає", () => {
    expect(detectOffPage([nested(OVERSIZE, "Spread")], [page()])).toHaveLength(1);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: елемент У ГРУПІ судиться як раніше — група не кадрує", () => {
    expect(detectOffPage([nested(OVERSIZE, "Group")], [page()])).toHaveLength(1);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: прив'язаний об'єкт судиться як раніше", () => {
    expect(detectOffPage([nested(OVERSIZE, "Character")], [page()])).toHaveLength(1);
  });
});

/**
 * НЕДОТЯГНУТИЙ ВИЛІТ — питання, протилежне до `frame-off-page`, і корисне
 * саме воно: чи заповнює елемент виліт.
 *
 * Елемент, який перетинає лінію ОБРІЗУ, буде розрізаний. Якщо він при цьому
 * не доходить до лінії ВИЛЬОТУ, різак із похибкою лишить білу смужку по краю.
 * Це справжній друкарський дефект, на відміну від виходу ЗА виліт (там зайве
 * просто зрізається).
 *
 * Еталон береться з документа (`bleedBox`), тобто правило переносне між
 * виданнями; порога тут не треба — недобір це факт, а не судження.
 */
describe("detectBleedShort", () => {
  it("перетнув обріз, але не дійшов до вильоту — знахідка з величиною недобору", () => {
    /* Ліворуч доходить до −4 при вильоті −8.50393700787402: недобір 4.5 pt. */
    const found = detectBleedShort([item([-8.5, -4, 632.126, 538.582677165354])], [page()]);
    expect(found).toHaveLength(1);
    expect(found[0]?.defect).toBe("bleed-short");
    expect(found[0]?.value).toBe("4.50 pt");
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: рівно у виліт — знахідки немає", () => {
    /* ЧИСЛА ТОЧНІ, А НЕ ОКРУГЛЕНІ, і це не педантизм. Перша редакція тесту
     * узяла −8.5 замість виміряного −8.50393700787402 і впала: 0.0039 pt
     * недобору справді більші за EPSILON (0.001, розрахований на шум
     * подвійної точності 7e-12). Хибним був ТЕСТ, не детектор — справжні
     * рамки книжки лежать на вильоті з точністю до 1e-11 (виміряно
     * 2026-08-16: с. 2 дає [−8.5039370078739, −8.50393700787401,
     * 632.125984251969, 538.582677165354]). */
    const exact: [number, number, number, number] = [
      -8.50393700787402, -8.50393700787402, 632.125984251969, 538.582677165354,
    ];
    expect(detectBleedShort([item(exact)], [page()])).toHaveLength(0);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: елемент, що обрізу не перетинає, поза питанням", () => {
    /* Звичайна рамка всередині смуги нічого заповнювати не мусить. */
    expect(detectBleedShort([item([50, 50, 300, 300])], [page()])).toHaveLength(0);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: елемент, що вийшов ЗА виліт, недобору не має", () => {
    expect(detectBleedShort([item([-20, -20, 650, 560])], [page()])).toHaveLength(0);
  });

  it("вкладений вміст сюди не потрапляє — судиться рамка, не оригінал", () => {
    expect(detectBleedShort([nested([-8.5, -4, 632.126, 538.582677165354], "Rectangle")], [page()])).toHaveLength(0);
  });

  it("внутрішній бік verso вильоту не має — недобору там не буває", () => {
    /* inside = 0, тобто лінія вильоту збігається з обрізом: рамка, що дійшла
     * рівно до корінця, дотягнула повністю. */
    const exact: [number, number, number, number] = [
      -8.50393700787402, -8.50393700787402, 632.125984251969, 538.582677165354,
    ];
    expect(detectBleedShort([item(exact)], [page("left")])).toHaveLength(0);
  });
});

/*
 * ЩО НЕ ДРУКУЄТЬСЯ, ТЕ НЕ МОЖЕ ЗІЙТИ З АРКУША.
 *
 * `layerVisible`/`layerPrintable` міряються, але їх читав рівно один детектор
 * — `wrap.ts`. Напрямна на схованому шарі, накреслена за виліт, давала
 * frame-off-page про об'єкт, якого на аркуші не буде.
 * `color_audit` тримає протилежну політику з ВИМІРЯНИМ обґрунтуванням: вісім
 * елементів форзаца в 100 % ціану на непринтованому шарі, і «детектор без
 * цього поля дав би вісім порушень на правильно зібраному файлі».
 */
describe("невидимі й непринтовані шари", () => {
  const ДАЛЕКО: [number, number, number, number] = [-200, -200, -100, -100];
  const наШарі = (over: Partial<ItemMeasure>): ItemMeasure => ({ ...item(ДАЛЕКО), ...over });

  it("схований шар знахідки не дає", () => {
    expect(detectOffPage([наШарі({ layerVisible: false })], [page()])).toEqual([]);
  });

  it("непринтований шар знахідки не дає", () => {
    expect(detectOffPage([наШарі({ layerPrintable: false })], [page()])).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: той самий елемент на друкованому шарі — дає", () => {
    /* Інакше правка звелася б до «родина frame мовчить». */
    expect(detectOffPage([item(ДАЛЕКО)], [page()]).length).toBeGreaterThan(0);
  });
});
