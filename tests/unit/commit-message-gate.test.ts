interface MessageHit {
  commit: string;
  subject: string;
  what: string;
  text: string;
}

function git(args: string[]): string {
  return execFileSync("git", args, {
    cwd: ROOT,
    maxBuffer: 64 * 1024 * 1024,
    stdio: ["ignore", "pipe", "ignore"],
  }).toString("utf8");
}

/** Усі коміти цієї лінії. Відсів відомих — уже в `scanMessages`. */
function allCommits(): Array<{ sha: string; subject: string; body: string }> {
  /*
   * НЕГЛИБОКИЙ КЛОН — ЦЕ НЕ «ІСТОРІЯ ЧИСТА», А «ІСТОРІЇ НЕ ВИДНО».
   *
   * `actions/checkout` за замовчуванням бере `fetch-depth: 1`, тобто ОДИН
   * коміт. Ворота на такому клоні зеленіли б, оглянувши верхівку, і зелень
   * читалася б як «у повідомленнях нічого немає». Тому відмова гучна, а в
   * `.github/workflows/ci.yml` стоїть `fetch-depth: 0`.
   */
  if (git(["rev-parse", "--is-shallow-repository"]).trim() === "true") {
    throw new Error(
      "Репозиторій неглибокий: історії комітів не видно, тож перевіряти нема що. " +
        "У CI поставте `fetch-depth: 0` для actions/checkout. " +
        "Мовчки пропускати не можна: зелений набір читався б як «у повідомленнях нічого немає».",
    );
  }

  /* \x1e між комітами, \x1f між полями — жоден із них не буває в тексті. */
  const raw = git(["log", "--format=%H%x1f%s%x1f%b%x1e"]);
  return raw
    .split("\x1e")
    .map((chunk) => chunk.replace(/^\n/u, ""))
    .filter((chunk) => chunk.trim() !== "")
    .map((chunk) => {
      const [sha = "", subject = "", body = ""] = chunk.split("\x1f");
      return { sha, subject, body };
    });
}

function scanMessages(): MessageHit[] {
  const hits: MessageHit[] = [];
  for (const c of allCommits()) {
    if (KNOWN_DIRTY.has(c.sha)) continue;
    for (const line of `${c.subject}\n${c.body}`.split("\n")) {
      /*
       * `file` НЕ передається навмисно: у повідомленні коміта файла немає, а
       * виняток для рядка авторського права прив'язаний саме до `LICENSE`.
       * Передати сюди щось схоже означало б відкрити виняток там, де він не
       * має підстави.
       */
      for (const h of detectPrivate(line)) {
        hits.push({ commit: c.sha.slice(0, 8), subject: c.subject.slice(0, 60), ...h });
      }
    }
  }
  return hits;
}

describe("у повідомленнях нових комітів немає приватних даних", () => {
  it("історія взагалі видно", () => {
    /*
     * Негативний контроль на прилад: якби `git log` віддав порожньо, перевірка
     * нижче зеленіла б на нулі комітів — рівно та «перевірка, що не може
     * впасти», проти якої написані обидві ворота.
     *
     * ПОРІГ САМЕ В ОДИН КОМІТ, і це не поблажливість. Перша редакція вимагала
     * більш ніж чотирьох, і це протрималося рівно до першого переписування
     * історії начисто: у переписаній лінії комітів законно один. Кількість
     * комітів узагалі не свідчить про глибину клону — про неї свідчить
     * `--is-shallow-repository` вище, і саме там стоїть відмова.
     */
    expect(allCommits().length).toBeGreaterThan(0);
  });

  it("перелік відомих не роздувся тихцем", () => {
    /*
     * Кожен рядок у ньому — свідоме рішення лишити коміт як є. Якби перелік
     * ріс від зручності, ворота зеленіли б, пропускаючи дедалі більше.
     */
    expect(KNOWN_DIRTY.size).toBe(27);
  });

  it("ДЕТЕКТОР СПРАЦЬОВУЄ: позитивний близнюк на кожну форму", () => {
    /*
     * Без цього ворота могли б тихо стати пустушкою — досить одного промаху в
     * імпорті, і `detectPrivate` повертав би порожньо на всьому.
     *
     * Взірці ВИГАДАНІ: справжніх приватних даних тут немає й бути не може, бо
     * цей файл сам відстежується файловими воротами.
     */
    const specimens: Array<[string, RegExp]> = [
      ["правка у /Users/kyrylo/Documents/x", /домівк/u],
      ["звірено з real.person@gmail.com", /пошт/u],
      ["ISBN 978-617-9999-99-9 у вихідних", /ISBN/u],
      ["шлях GoogleDrive-real.person@gmail.com/My Drive", /Drive/u],
      ["виправлено назву Chiiiiiicken.indd", /назву конкретного видання/u],
    ];
    for (const [line, expected] of specimens) {
      const what = detectPrivate(line).map((h) => h.what).join(" | ");
      expect(what, `взірець не спійманий: ${line}`).toMatch(expected);
    }

    /* І контроль у другий бік: звичайне повідомлення НЕ ловиться. */
    expect(detectPrivate("Chicago: сегментатор без номерів, і негативний доказ")).toEqual([]);
  });

  it("жодне нове повідомлення не несе приватного", () => {
    const hits = scanMessages();
    expect(
      hits,
      hits.length === 0
        ? ""
        : `приватне у повідомленнях комітів (${hits.length}):\n` +
          hits
            .map((h) => `  ${h.commit} «${h.subject}» — ${h.what}\n      ${h.text}`)
            .join("\n") +
          "\n\nОстаннє правлять через `git commit --amend`. Глибше — інтерактивний " +
          "rebase, і це зміна всіх наступних хешів. Дописувати SHA до KNOWN_DIRTY " +
          "заради зеленого — саме те, проти чого ці ворота написані.",
    ).toEqual([]);
  });
});
