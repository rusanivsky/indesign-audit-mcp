/**
 * Зони, де типографське правило ЛАМАЛО ПРАВИЛЬНЕ.
 *
 * Усі чотири випадки — з прогону по робочій книжці 2026-08-15 і з поправок
 * користувача. Спільна природа в них одна: правило судить текст у відриві від
 * того, ЧИМ цей текст є на сторінці — цитатою в плашці, вихідними даними,
 * кодом ISBN, невидимим службовим символом. Жодну з чотирьох не було видно
 * з самого рядка символів.
 */
import { describe, expect, it } from "vitest";
import { runRules } from "../../src/typography/engine.js";
import { DASH_RULES, QUOTE_RULES, SPACING_RULES } from "../../src/typography/rules-uk.js";

const ids = (text: string, rules: typeof SPACING_RULES) => runRules(text, rules).map((m) => m.ruleId);

describe("U+FEFF — не пробіл", () => {
  /* Виміряно: 9 знахідок `collapse-spaces` із 10 на книжці мали вигляд
   * [U+FEFF U+FEFF] → [U+0020], тобто заміна ВСТАВИЛА Б видимий пробіл
   * перед заголовком розділу, де його не було. Підтверджено й оком:
   * експорт с. 21 показує «ВАГІТНІСТЬ» без жодного відступу. */
  it("два U+FEFF поспіль НЕ є двома пробілами", () => {
    expect(ids("﻿﻿Передмова", SPACING_RULES)).toEqual([]);
  });

  it("U+FEFF перед знаком абзацу не є пробілом перед знаком абзацу", () => {
    expect(ids("БАДи.﻿\rдалі", SPACING_RULES)).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: справжні два пробіли згортаються як і раніше", () => {
    expect(ids("мама  і тато", SPACING_RULES)).toContain("collapse-spaces");
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: справжній пробіл перед знаком абзацу ловиться", () => {
    expect(ids("рядок \rдалі", SPACING_RULES)).toContain("space-before-break");
  });
});

describe("ISBN — не числовий діапазон", () => {
  /* Виміряно на с. 4: ISBN 978-966-1234-56-7. Правило бачило два «діапазони»
   * (978-966 і 1234-56) і дало б 978–966-1234–56-7, тобто зіпсований ISBN на
   * сторінці вихідних даних. Ознака коду, а не діапазону: ланцюжок
   * цифр-через-дефіс ПРОДОВЖУЄТЬСЯ за межі збігу. */
  it("ISBN не чіпається взагалі", () => {
    expect(ids("ISBN 978-966-1234-56-7", DASH_RULES)).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: справжній діапазон років правиться", () => {
    expect(ids("1941-1945 роки", DASH_RULES)).toContain("range-dash-numeric");
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: діапазон із граматичним закінченням правиться", () => {
    /* «10-11-му тижні» — дефіс після діапазону веде до ЛІТЕРИ, не до цифри,
     * тобто ланцюжок коду не продовжується. Ця форма в книжці реальна
     * (с. 24: «на 10–11-му тижні»), тож відсікати її разом з ISBN не можна. */
    expect(ids("на 10-11-му тижні", DASH_RULES)).toContain("range-dash-numeric");
  });
});

describe("«ялинки» проти вкладених “англійських”", () => {
  /* Виміряно: 8 знахідок із 8 хибні. На с. 24 цитата лежить у ПЛАШЦІ з
   * декоративною лапкою 150 pt — зовнішній рівень цитати виражений ГРАФІЧНО,
   * а не символом. Тому “ ” там — законний другий рівень, і заміна на « »
   * зламала б норму. З тексту цього не видно в принципі. */
  it("«...» усередині “...” лишається лише КАНДИДАТОМ, не певною правкою", () => {
    const found = runRules("щастя:) “Боже, невже я правда ношу…” Руки тремтіли", QUOTE_RULES);
    expect(found.length).toBeGreaterThan(0);
    expect(found.every((m) => m.confidence === "needs-review")).toBe(true);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: пряма ASCII-лапка лишається певною правкою", () => {
    /* Пряма лапка в українському наборі неправильна ЗАВЖДИ, хоч би який
     * рівень вкладення, — тут вагатися нема чого. */
    const found = runRules('роман "Мати" тут', QUOTE_RULES);
    expect(found.length).toBeGreaterThan(0);
    expect(found.every((m) => m.confidence === "high")).toBe(true);
  });
});

describe("бібліографічний опис — інша норма, ніж текст", () => {
  /* Виміряно на с. 4: «Назва книжки / Автор Авторенко. — Київ :⏎ВИДАВНИЦТВО,
   * 2026. — 196 с.» Пробіл перед двокрапкою тут ПРИПИСАНИЙ
   * ДСТУ, а не помилка набору. Ознака, доступна з тексту: двокрапка стоїть
   * ОКРЕМО — пробільне з обох боків. У звичайній прозі такого не буває. */
  it("двокрапка з пробілом з ОБОХ боків не чіпається", () => {
    expect(ids("— Київ : ВИДАВНИЦТВО", SPACING_RULES)).toEqual([]);
  });

  it("те саме, коли після двокрапки йде розрив рядка", () => {
    expect(ids("— Київ :\nВИДАВНИЦТВО", SPACING_RULES)).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: звичайний пробіл перед двокрапкою ловиться", () => {
    expect(ids("слово :інше", SPACING_RULES)).toContain("space-before-punct");
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: кома з пробілом з обох боків — усе одно помилка", () => {
    /* Виняток стосується ЛИШЕ двокрапки та крапки з комою: приписана
     * пунктуація ДСТУ вживає саме ці два знаки, а кома окремо не стоїть у
     * жодній нормі. */
    expect(ids("так , ось", SPACING_RULES)).toContain("space-before-punct");
  });

  /*
   * КРАПКА З КОМОЮ — ТА САМА НОРМА, І ЇЇ БРАКУВАЛО ДО 2026-08-26.
   *
   * ДСТУ 7.1 приписує пробіли коло крапки з комою у двох місцях: між місцями
   * видання («— Київ ; Харків : ТОВ») і між другим та дальшими відомостями
   * про відповідальність («/ Автор Авторенко ; ред. Р. Редакторенко»). Те саме
   * стверджує й наш власний slashOnceRule у src/bibliography/rules-dstu.ts.
   *
   * Виняток покривав лише двокрапку, тож два пакети правил суперечили одне
   * одному на сторінці вихідних відомостей удруге — на один знак далі.
   * Зміряно на тому самому рядку: ДВА збіги, обидва «high», а
   * typography_apply пише «high» без перегляду — тобто це був мовчазний
   * запис у книжку користувача, а не шум у звіті.
   */
  it("крапка з комою з пробілом з ОБОХ боків не чіпається", () => {
    expect(ids("— Київ ; Харків : ТОВ", SPACING_RULES)).toEqual([]);
  });

  it("крапка з комою у відомостях про відповідальність не чіпається", () => {
    expect(ids("/ Автор Авторенко ; ред. Р. Редакторенко", SPACING_RULES)).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: звичайний пробіл перед крапкою з комою ловиться", () => {
    /* Без цього виняток міг би тихо вимкнути правило для знака назовсім:
     * ознака — «пробільне з обох боків», а не сам знак. */
    expect(ids("слово ;інше", SPACING_RULES)).toContain("space-before-punct");
  });
});

/*
 * ЗВОРОТНА ГІЛКА ЗАХИСТУ КОДІВ — та, що дивиться НАЗАД.
 *
 * `except` у range-dash-numeric має дві дзеркальні перевірки: чи ланцюжок
 * «цифри-через-дефіс» продовжується ПІСЛЯ збігу і чи він продовжується ПЕРЕД
 * ним. Пряма покриває ланцюжки непарної довжини, зворотна — парної, і саме
 * зворотна не мала тесту: мутаційна проба 2026-08-26 показала, що її можна
 * прибрати цілком, і ввесь набір лишався зеленим.
 *
 * Правило має confidence «high», тобто typography_apply пише його без
 * перегляду, — отже незакрита гілка означала мовчазне псування кодів.
 */
describe("ланцюжок коду, що продовжується ПЕРЕД збігом", () => {
  /*
   * Форму ISBN тут НЕ повторюємо: ланцюжок парної довжини — це те саме, що
   * «код 1-2-3-4», а обрізаний ISBN спіймали б ворота приватності
   * (tests/unit/privacy-gate.test.ts), і слушно: від справжнього коду
   * видання вони його відрізнити не можуть.
   */
  it.each([
    "код 1-2-3-4",
    "1-2-3",
  ])("%s не чіпається", (текст) => {
    expect(ids(текст, DASH_RULES)).toEqual([]);
  });

  it("ПОЗИТИВНИЙ БЛИЗНЮК: справжній діапазон із двох членів правиться", () => {
    /* Інакше правка звелася б до «числові діапазони не правляться ніколи». */
    expect(ids("1941-1945", DASH_RULES)).toContain("range-dash-numeric");
  });
});
