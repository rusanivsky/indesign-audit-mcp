import { closeStrayFixtureDocs, type OpenDoc } from "./fixture-doc.js";

/*
 * СІТКА ПІД УСІМ ІНТЕГРАЦІЙНИМ ПРОГОНОМ: жоден із них не має лишати по собі
 * відкритий документ.
 *
 * ЧОМУ ЦЬОГО НЕ РОБЛЯТЬ САМІ ФАЙЛИ (вони й роблять — але не все). `afterEach`
 * у кожному файлі закриває свою фікстуру, і виконується він навіть після
 * падіння тесту (доведено виконанням на vitest 3.2.7). Лишаються два випадки,
 * до яких `afterEach` не дотягується:
 *
 *   1. сам `closeFixtureDoc` упав — InDesign був зайнятий, міст здався за
 *      таймаутом; документ лишився відкритим, і про це ніхто не сказав;
 *   2. прогін урвався (Ctrl-C, вбитий воркер) — тоді не виконується ані
 *      `afterEach`, ані `teardown` нижче (виміряно 2026-08-16: на SIGINT
 *      vitest 3.2.7 teardown НЕ виконує).
 *
 * Перший випадок закриває `teardown`. Другий — `setup`: наступний прогін
 * починається з прибирання, тож забуті документи НЕ НАКОПИЧУЮТЬСЯ за день.
 * Саме накопичення й коштує дорого: довга сесія InDesign роздуває важкий вимір
 * у 12–29 разів, тобто хронометраж після кількох прогонів уже нічого не варт.
 *
 * ЩО САМЕ ЗАКРИВАЄТЬСЯ — вирішує `isStrayFixtureDoc`: назва з чотирьох
 * названих плюс тимчасова тека з нашим префіксом. Робочий документ користувача
 * не проходить жодної з умов.
 *
 * ПРО ЗМІННУ СЕРЕДОВИЩА. `INDESIGN_MCP_FIXTURES` вмикає завантаження
 * `_fixtures.jsx` (без нього обробника закриття просто немає). Проєкт
 * "integration" задає її ТЕСТОВИМ ВОРКЕРАМ, а цей файл виконується в
 * головному процесі vitest, тож тут її треба поставити явно — це той самий
 * гейт, а не його послаблення: файл підключений лише з проєкту "integration".
 */
function report(stage: string, stray: OpenDoc[]): void {
  if (stray.length === 0) return;
  const list = stray.map((d) => `${d.name} (${d.fullName})`).join("\n  ");
  console.warn(
    `\n[фікстури] ${stage}: закрито ЗАБУТИХ документів — ${stray.length}.\n  ${list}\n` +
      "  Це сліди прогону, який не прибрав за собою; шукати треба причину, а не лише наслідок.\n",
  );
}

async function sweep(stage: string): Promise<void> {
  process.env.INDESIGN_MCP_FIXTURES = "1";
  try {
    report(stage, await closeStrayFixtureDocs());
  } catch (err) {
    /* InDesign може бути не запущений — тоді впадуть і самі тести, зі своєю,
     * зрозумілішою помилкою. Прибирання не має права стати ПЕРШОЮ причиною
     * падіння прогону, тож тут лише голосно повідомляємо. */
    console.warn(`[фікстури] ${stage}: прибрати не вдалося — ${String(err)}`);
  }
}

export async function setup(): Promise<void> {
  await sweep("перед прогоном");
}

export async function teardown(): Promise<void> {
  await sweep("після прогону");
}
